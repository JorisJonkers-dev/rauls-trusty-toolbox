"""Puts the site's navbar on the chart page that github-action-benchmark writes (bench/raw/index.html on gh-pages).

The page is generated by the action, so the navbar is added after each write: this script is idempotent (the added
markup sits between markers and is replaced, never doubled).

    python3 site/bench_raw.py <folder holding raw/index.html, e.g. a gh-pages checkout's bench/>
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import shell  # noqa: E402

UP = "../../"
HEAD_MARK = ("<!--site-head-->", "<!--/site-head-->")
BODY_MARK = ("<!--site-header-->", "<!--/site-header-->")


def _strip(text: str, mark: tuple[str, str]) -> str:
    return re.sub(re.escape(mark[0]) + r".*?" + re.escape(mark[1]) + r"\n?", "", text, flags=re.S)


def shelled(text: str) -> str:
    text = _strip(_strip(text, HEAD_MARK), BODY_MARK)
    head = f'{HEAD_MARK[0]}<link rel="stylesheet" href="{UP}assets/site.css">{HEAD_MARK[1]}\n'
    body = f"{BODY_MARK[0]}{shell.header('bench', UP)}{BODY_MARK[1]}\n"
    if "</head>" in text:
        text = text.replace("</head>", head + "</head>", 1)
    else:
        text = head + text
    m = re.search(r"<body[^>]*>", text)
    if m:
        return text[: m.end()] + "\n" + body + text[m.end():]
    return text + body


def apply(bench_dir: Path) -> bool:
    page = bench_dir / "raw" / "index.html"
    if not page.is_file():
        return False
    page.write_text(shelled(page.read_text()))
    return True


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    print("navbar added to bench/raw/" if apply(Path(sys.argv[1])) else "no raw page here")
