//! The install plan: for each Mod of a list, whether the Instance has it, and if not where to get it. Nothing here
//! reads a disk or calls a network; the caller says which Mods are present and may plug in a [`FileResolver`].

use std::collections::BTreeSet;

use serde::Serialize;

use crate::model::{ModList, Source};

/// Where a file id comes from when the list does not carry one. The Nexus client implements this; until it does,
/// [`NoResolver`] is used and the plan links the Mod's files page instead of the file.
pub trait FileResolver {
    /// The Nexus file id for a Mod whose list entry has no `file`, found by the upload time or the archive name.
    fn nexus_file(
        &self,
        game: &str,
        mod_id: u64,
        uploaded: Option<u64>,
        file_name: Option<&str>,
    ) -> Option<u64>;
}

/// A resolver that finds nothing.
#[derive(Debug, Clone, Copy, Default)]
pub struct NoResolver;

impl FileResolver for NoResolver {
    fn nexus_file(&self, _: &str, _: u64, _: Option<u64>, _: Option<&str>) -> Option<u64> {
        None
    }
}

/// Where one Mod stands.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum State {
    /// The Instance already has it.
    Present,
    /// The Instance lacks it and the list wants it.
    Missing,
    /// The list switches it off, so nothing is needed.
    Skipped,
}

/// How a missing Mod is obtained.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(tag = "how", rename_all = "lowercase")]
pub enum Acquire {
    /// Download from Nexus Mods; `page` opens the file (or the Mod's files when the id is unknown).
    Nexus {
        /// The address to open.
        page: String,
        /// The file id, when known.
        file_id: Option<u64>,
        /// The archive's name, when known.
        file_name: Option<String>,
        /// The archive's size, when known.
        size: Option<u64>,
    },
    /// Download from this address.
    Link {
        /// The address.
        url: String,
        /// The archive's name, when known.
        file_name: Option<String>,
        /// What to know before downloading.
        note: Option<String>,
    },
    /// The person has to find the file; the list says what it can.
    Manual {
        /// The archive's name, when known.
        file_name: Option<String>,
        /// What to know.
        note: Option<String>,
    },
    /// Built by a Component from the person's own files.
    Tool {
        /// The Component.
        tool: String,
    },
    /// Generated by a Component after the other Mods are in.
    Generated {
        /// The Component.
        tool: String,
    },
    /// One of raul's own add-ons.
    Addon {
        /// The add-on's id.
        id: String,
    },
}

/// One line of the plan.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Item {
    /// Place in the list, 1 is the lowest priority and goes in first.
    pub position: usize,
    /// The Mod's id in the list.
    pub id: String,
    /// The Mod folder name.
    pub name: String,
    /// The group id, when the Mod has one.
    pub group: Option<String>,
    /// Where it stands.
    pub state: State,
    /// How to get it; `None` for a Mod that is present or skipped.
    pub acquire: Option<Acquire>,
}

/// How many Mods are in each state.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub struct Counts {
    /// Present in the Instance.
    pub present: usize,
    /// Missing.
    pub missing: usize,
    /// Switched off by the list.
    pub skipped: usize,
}

/// The whole plan.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Plan {
    /// The list's id.
    pub list: String,
    /// The list's name.
    pub name: String,
    /// Every Mod of the list, in install order.
    pub items: Vec<Item>,
}

impl Plan {
    /// The Mods to get, in the order they are installed.
    pub fn missing(&self) -> impl Iterator<Item = &Item> {
        self.items.iter().filter(|i| i.state == State::Missing)
    }

    /// How many Mods are in each state.
    #[must_use]
    pub fn counts(&self) -> Counts {
        let n = |s: State| self.items.iter().filter(|i| i.state == s).count();
        Counts {
            present: n(State::Present),
            missing: n(State::Missing),
            skipped: n(State::Skipped),
        }
    }
}

/// The plan of `list` for an Instance that has the Mods named in `present` (compared without regard to case).
#[must_use]
pub fn plan(list: &ModList, present: &[String], resolver: &dyn FileResolver) -> Plan {
    let have: BTreeSet<String> = present.iter().map(|n| n.to_lowercase()).collect();
    let items = list
        .mods
        .iter()
        .enumerate()
        .map(|(i, m)| {
            let (state, acquire) = if !m.enabled {
                (State::Skipped, None)
            } else if have.contains(&m.name.to_lowercase()) {
                (State::Present, None)
            } else {
                (State::Missing, Some(acquire(&m.source, resolver)))
            };
            Item {
                position: i + 1,
                id: m.id.clone(),
                name: m.name.clone(),
                group: m.group.clone(),
                state,
                acquire,
            }
        })
        .collect();
    Plan {
        list: list.id.clone(),
        name: list.name.clone(),
        items,
    }
}

fn acquire(source: &Source, resolver: &dyn FileResolver) -> Acquire {
    match source {
        Source::Nexus {
            game,
            mod_id,
            file,
            file_name,
            size,
            uploaded,
            ..
        } => {
            let file_id = file
                .or_else(|| resolver.nexus_file(game, *mod_id, *uploaded, file_name.as_deref()));
            Acquire::Nexus {
                page: nexus_page(game, *mod_id, file_id),
                file_id,
                file_name: file_name.clone(),
                size: *size,
            }
        }
        Source::Url { url, file_name, .. } => Acquire::Link {
            url: url.clone(),
            file_name: file_name.clone(),
            note: None,
        },
        Source::Manual {
            url: Some(url),
            file_name,
            note,
        } => Acquire::Link {
            url: url.clone(),
            file_name: file_name.clone(),
            note: note.clone(),
        },
        Source::Manual {
            url: None,
            file_name,
            note,
        } => Acquire::Manual {
            file_name: file_name.clone(),
            note: note.clone(),
        },
        Source::Tool { tool, .. } => Acquire::Tool { tool: tool.clone() },
        Source::Generated { tool } => Acquire::Generated { tool: tool.clone() },
        Source::Addon { id } => Acquire::Addon { id: id.clone() },
    }
}

/// The page that shows a Nexus file, or the Mod's files tab when the file is not known.
#[must_use]
pub fn nexus_page(game: &str, mod_id: u64, file_id: Option<u64>) -> String {
    let base = format!("https://www.nexusmods.com/{game}/mods/{mod_id}?tab=files");
    file_id.map_or(base.clone(), |f| format!("{base}&file_id={f}"))
}
