//! The install steps of a list (ADR-0023, #681): which Mods go into the Profile, in what order, and where each one goes
//! in `modlist.txt`. Nothing here reads a disk or calls a Component; the caller says which Mods the Instance has and
//! which archives it holds, and does the installs.
//!
//! A list is ordered lowest priority first (a later Mod wins a file conflict) and `modlist.txt` lists the highest
//! priority first. Mods are installed in list order, so each new Mod must land above everything installed before it
//! and below every later Mod of the list that is already there: [`Place::After`] the nearest later Mod the Instance
//! has, or [`Place::Top`] when it has none.

use std::collections::BTreeSet;

use serde::Serialize;

use crate::model::{ModList, Source};

/// Where a Mod goes in `modlist.txt`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(tag = "at", content = "mod", rename_all = "lowercase")]
pub enum Place {
    /// First: the highest priority so far.
    Top,
    /// Right under this Mod, so below it.
    After(String),
}

/// One Mod to install.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Step {
    /// Place in the list, 1 is the lowest priority and goes in first.
    pub position: usize,
    /// The Mod's id in the list.
    pub id: String,
    /// The Mod folder name.
    pub name: String,
    /// The archive's file name in the downloads folder, as it is spelled there.
    pub archive: String,
    /// Where it goes in `modlist.txt`.
    pub place: Place,
    /// Whether it is switched on afterwards (the list's `enabled`).
    pub enabled: bool,
}

/// A Mod the list wants that has no archive to install.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Missing {
    /// Place in the list.
    pub position: usize,
    /// The Mod's id.
    pub id: String,
    /// The Mod folder name.
    pub name: String,
    /// The archive name the list gives, when it gives one.
    pub archive: Option<String>,
}

/// A Mod this step does not install: built or generated by a Component, or one of raul's add-ons.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Elsewhere {
    /// Place in the list.
    pub position: usize,
    /// The Mod's id.
    pub id: String,
    /// The Mod folder name.
    pub name: String,
}

/// What installing a list into an Instance comes to.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct InstallPlan {
    /// The list's id.
    pub list: String,
    /// Mods to install, in the order they go in.
    pub steps: Vec<Step>,
    /// Mods the list wants whose archive is not there.
    pub missing: Vec<Missing>,
    /// Mods built or generated elsewhere.
    pub elsewhere: Vec<Elsewhere>,
    /// How many Mods the Instance has already.
    pub present: usize,
    /// How many Mods are switched off by the list and not in the Instance, with no archive to stage.
    pub skipped: usize,
}

fn archive_name(source: &Source) -> Option<&str> {
    match source {
        Source::Nexus { file_name, .. }
        | Source::Url { file_name, .. }
        | Source::Manual { file_name, .. } => file_name.as_deref(),
        Source::Tool { .. } | Source::Generated { .. } | Source::Addon { .. } => None,
    }
}

/// The steps to install `list` into an Instance that has the Mods `present` and the archives `archives` (file names
/// in the downloads folder). Names are compared without regard to case.
#[must_use]
pub fn plan_install(list: &ModList, present: &[String], archives: &[String]) -> InstallPlan {
    let have: BTreeSet<String> = present.iter().map(|n| n.to_lowercase()).collect();
    let mut plan = InstallPlan {
        list: list.id.clone(),
        steps: Vec::new(),
        missing: Vec::new(),
        elsewhere: Vec::new(),
        present: 0,
        skipped: 0,
    };
    for (i, m) in list.mods.iter().enumerate() {
        let position = i + 1;
        if have.contains(&m.name.to_lowercase()) {
            plan.present += 1;
            continue;
        }
        let wanted = archive_name(&m.source);
        let found = wanted.and_then(|w| archives.iter().find(|a| a.eq_ignore_ascii_case(w)));
        if let Some(archive) = found {
            let place = list.mods[i + 1..]
                .iter()
                .find(|later| have.contains(&later.name.to_lowercase()))
                .map_or(Place::Top, |later| Place::After(later.name.clone()));
            plan.steps.push(Step {
                position,
                id: m.id.clone(),
                name: m.name.clone(),
                archive: archive.clone(),
                place,
                enabled: m.enabled,
            });
        } else if !m.enabled {
            plan.skipped += 1;
        } else if wanted.is_none()
            && matches!(
                m.source,
                Source::Tool { .. } | Source::Generated { .. } | Source::Addon { .. }
            )
        {
            plan.elsewhere.push(Elsewhere {
                position,
                id: m.id.clone(),
                name: m.name.clone(),
            });
        } else {
            plan.missing.push(Missing {
                position,
                id: m.id.clone(),
                name: m.name.clone(),
                archive: wanted.map(str::to_owned),
            });
        }
    }
    plan
}
