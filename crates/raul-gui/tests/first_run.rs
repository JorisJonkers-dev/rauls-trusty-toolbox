//! First run to a sorted load order, end to end, with no profile action anywhere: the setup wizard makes the
//! Instance and its default profile itself, and the Load order page sorts without ever asking for one.
//!
//! The window runs on the release `raul` on a synthetic Instance. The masterlist is a file written here, which the
//! fixture's command passes where the pages ask for the pinned one, so nothing is fetched.
#![cfg(unix)]
#![allow(clippy::disallowed_methods)]

use egui_kittest::Harness;
use egui_kittest::kittest::Queryable;
use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, write_file};
use raul_core::context::Context;
use raul_gui::catalogue as msg;
use raul_gui::jobs::Jobs;
use raul_gui::pages::load_order::SORT;
use raul_gui::pages::setup::{NEXT, SET_UP_INSTANCE};
use raul_gui::shell::App;
use raul_ui_service::{Exec, InProcessExec};
use std::path::PathBuf;
use std::sync::Arc;
use std::time::Duration;

const MASTERLIST: &str = "plugins:\n  - name: 'Other\\.esp'\n    msg:\n      - {type: warn, content: 'A synthetic warning'}\n";
const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

struct Fixture {
    root: TempDir,
}

impl Fixture {
    /// A first run: the game is found, nothing else is set, and no Instance exists yet.
    fn new() -> Fixture {
        let f = Fixture {
            root: TempDir::new("gui-first-run"),
        };
        let base = f.path("base");
        BaseBuilder::steam().write(&base);
        write_file(
            &base,
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        // The game folder has xNVSE in it, as a copy that ran modded does: the Quick check must not judge it.
        write_file(&base, "nvse_loader.exe", b"MZ");
        write_file(&base, "nvse_1_4.dll", b"MZ");
        std::fs::write(f.path("masterlist.yaml"), MASTERLIST).unwrap();
        f.raul(&["config", "set", "game.newvegas", &f.s("base")]);
        f.raul(&["config", "set", "storage.root", &f.s("storage")]);
        f
    }

    /// The folders this fixture's runs use: its own configuration, and no run log, so nothing reaches the real home.
    fn context(&self) -> Context {
        Context::new()
            .with_config_folder(self.path("config"))
            .without_run_log()
    }

    /// The command line run in this process with this fixture's folders.
    fn exec(&self) -> InProcessExec {
        InProcessExec::with_context(self.context()).with_argument_replaced(
            "--fetch-masterlist",
            &["--masterlist", &self.s("masterlist.yaml")],
        )
    }

    fn path(&self, p: &str) -> PathBuf {
        self.root.path().join(p)
    }

    fn s(&self, p: &str) -> String {
        self.path(p).to_string_lossy().into_owned()
    }

    fn raul(&self, args: &[&str]) {
        let args: Vec<String> = args.iter().map(|a| (*a).to_owned()).collect();
        let out = self.exec().run(&args).unwrap();
        assert_eq!(out.code, Some(0), "{args:?}: {}", out.stderr);
    }

    fn instance(&self) -> PathBuf {
        self.path("storage/instance")
    }

    fn app(&self) -> Harness<'static, App> {
        let exec = self.exec();
        // The sort stays a command line here: the fixture's command swaps the pinned masterlist for a file, which a direct sort
        // (it fetches the pinned one itself) would not go through.
        let jobs = Jobs::new(Arc::new(exec))
            .with_context(self.context())
            .scripted(&["sort-preview", "sort-apply"]);
        let app = App::new(jobs);
        let mut h = Harness::builder()
            .with_size([1280.0, 800.0])
            .build_eframe(|cc| {
                raul_gui::set_up(&cc.egui_ctx);
                app
            });
        settle(&mut h);
        h
    }
}

/// The target the Instance file in `instance` names.
fn target_of(instance: &std::path::Path) -> String {
    let text = std::fs::read_to_string(instance.join("nvmod-instance.json")).unwrap();
    let record: serde_json::Value = serde_json::from_str(&text).unwrap();
    record["target"].as_str().unwrap().to_owned()
}

/// Runs frames until the jobs the window starts have ended and the pages have taken their answers.
fn settle(h: &mut Harness<'static, App>) {
    for _ in 0..6 {
        h.run_steps(8);
        assert!(h.state_mut().wait_for_jobs(Duration::from_secs(60)));
    }
    h.run_steps(8);
}

#[test]
fn first_run_sorts_the_load_order_with_no_profile_action() {
    let f = Fixture::new();
    assert!(!f.instance().exists(), "nothing is set up yet");
    let mut h = f.app();
    // The game is found already, so Home does not hand the run to the wizard; the setup strip does.
    h.state_mut().open(raul_ui_model::pages::View::Flow(
        raul_ui_model::pages::Flow::Setup,
    ));
    settle(&mut h);
    assert_eq!(
        h.state().view(),
        raul_ui_model::pages::View::Flow(raul_ui_model::pages::Flow::Setup),
        "the wizard is open"
    );

    // New Vegas folder, TTW, Instance: Set up makes the Instance and its default profile, then points it at the engine.
    for _ in 0..2 {
        h.get_by_label(NEXT).click();
        settle(&mut h);
    }
    h.get_by_label(SET_UP_INSTANCE).click();
    settle(&mut h);
    for _ in 0..200 {
        if f.instance().join("profiles/Default/modlist.txt").is_file() {
            break;
        }
        std::thread::sleep(Duration::from_millis(10));
        h.run_steps(2);
    }
    let list = f.instance().join("profiles/Default/modlist.txt");
    assert!(list.is_file(), "setup left a working default profile");
    settle(&mut h);

    // The wizard is left here: the Instance and its default profile are what the pages need, and Home is where
    // Open the Toolbox goes.
    h.state_mut().open(raul_ui_model::pages::View::Page(
        raul_ui_model::pages::PageId::Home,
    ));
    settle(&mut h);

    // A plugin to sort, written the way an install would leave it.
    write_file(
        &f.instance(),
        "mods/Other/Other.esp",
        &PluginBuilder::new().build(),
    );
    for name in ["modlist.txt", "plugins.txt", "loadorder.txt"] {
        let body = if name == "modlist.txt" {
            "+Other\r\n".to_owned()
        } else {
            "FalloutNV.esm\r\nOther.esp\r\n".to_owned()
        };
        write_file(
            &f.instance(),
            &format!("profiles/Default/{name}"),
            format!("{HEADER}{body}").as_bytes(),
        );
    }
    f.raul(&["stage", "--instance", &f.s("storage/instance")]);

    // Load order lists the plugins and sorts them, without one word about a profile.
    h.get_all_by_label(msg::PAGE_LOAD_ORDER)
        .next()
        .unwrap()
        .click();
    settle(&mut h);
    assert!(h.query_by_label("Other.esp").is_some(), "the list is shown");
    h.get_by_label(SORT).click();
    settle(&mut h);
    // The list is in the masterlist's order already, and the masterlist's message is shown beside its plugin.
    assert!(h.query_by_label("Already sorted").is_some(), "the sort ran");
    assert!(h.query_by_label("A synthetic warning").is_some());
    assert!(
        h.query_by_label_contains("rofile").is_none(),
        "no word about a profile on the page"
    );
    let written =
        std::fs::read_to_string(f.instance().join("profiles/Default/loadorder.txt")).unwrap();
    assert!(
        written.find("FalloutNV.esm").unwrap() < written.find("Other.esp").unwrap(),
        "the game's master comes first: {written}"
    );
}

#[test]
fn the_wizard_sets_the_target_to_the_engine_and_the_quick_check_ignores_xnvse() {
    let f = Fixture::new();
    // An Instance that exists already, left on the target `raul init` gives.
    f.raul(&[
        "init",
        "--base",
        &f.s("base"),
        "--instance",
        &f.s("storage/instance"),
    ]);
    assert_eq!(target_of(&f.instance()), "vanilla");
    let mut h = f.app();
    h.state_mut().open(raul_ui_model::pages::View::Flow(
        raul_ui_model::pages::Flow::Setup,
    ));
    settle(&mut h);

    // New Vegas folder, TTW, then the Instance step sets the target.
    for _ in 0..2 {
        h.get_by_label(NEXT).click();
        settle(&mut h);
    }
    h.get_by_label(SET_UP_INSTANCE).click();
    settle(&mut h);
    assert_eq!(
        target_of(&f.instance()),
        "nv-rs",
        "the wizard sets the target"
    );

    // The Quick check judges the engine: no word about xNVSE for the copy that has it in its folder.
    h.get_by_label(NEXT).click();
    settle(&mut h);
    assert!(
        h.query_by_label_contains("xNVSE").is_none(),
        "the Quick check judged the xNVSE path"
    );
}
