//! The Mods page end to end through the release `raul` on a synthetic Instance: it lists the Mods in priority order,
//! turns one off and on, moves one, removes one after asking, and gives the generated LOD Mod its own treatment
//! (tagged, Regenerate opens the LOD page, no Remove).
#![cfg(unix)]

use egui_kittest::Harness;
use egui_kittest::kittest::Queryable;
use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, write_file, write_script};
use raul_gui::catalogue as msg;
use raul_gui::jobs::Jobs;
use raul_gui::pages::mods::{
    DISABLE, DISABLED_STATUS, ENABLE, ENABLED_STATUS, GENERATED_NOTE, MOVE_UP, MOVED_STATUS,
    REGENERATE, REMOVE, REMOVE_ACTION, REMOVED_STATUS, TAG_GENERATED,
};
use raul_gui::shell::App;
use raul_ui_model::pages::{PageId, View};
use raul_ui_service::{Exec, ProcessExec};
use std::path::PathBuf;
use std::sync::Arc;
use std::time::Duration;

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";
const LOD: &str = "Generated LOD (Default)";

struct Fixture {
    root: TempDir,
}

impl Fixture {
    /// An Instance whose Profile lists `Alpha`, the generated LOD Mod and `Beta`, in that order.
    fn new() -> Fixture {
        let f = Fixture {
            root: TempDir::new("gui-mods"),
        };
        let base = f.path("base");
        BaseBuilder::steam().write(&base);
        write_file(
            &base,
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        write_script(
            f.root.path(),
            "raul",
            &format!(
                "export RAUL_CONFIG_DIR='{c}' NVMOD_STATE_DIR='{s}'\nexec '{raul}' \"$@\"",
                c = f.path("config").display(),
                s = f.path("state").display(),
                raul = env!("CARGO_BIN_EXE_raul"),
            ),
        );
        f.raul(&["config", "set", "storage.root", &f.s("storage")]);
        f.raul(&[
            "init",
            "--base",
            &f.s("base"),
            "--instance",
            &f.s("storage/instance"),
        ]);
        let instance = f.path("storage/instance");
        write_file(&instance, "mods/Alpha/readme.txt", b"alpha");
        write_file(&instance, "mods/Beta/readme.txt", b"beta");
        // What `raul lod generate` leaves: the Mod and the marker in its meta.ini.
        write_file(
            &instance,
            &format!("mods/{LOD}/lodsettings/sample.dlodsettings"),
            b"lod",
        );
        write_file(
            &instance,
            &format!("mods/{LOD}/meta.ini"),
            b"[General]\r\ngameName=newvegas\r\n[raulGeneratedLod]\r\ngenerated=true\r\nprofile=Default\r\nrequestDigest=sha256:00\r\nlodwrightVersion=0.3.0\r\n",
        );
        let list = |name: &str, lines: &[&str]| {
            let mut text = HEADER.to_owned();
            for l in lines {
                text.push_str(l);
                text.push_str("\r\n");
            }
            write_file(
                &instance,
                &format!("profiles/Default/{name}"),
                text.as_bytes(),
            );
        };
        list("modlist.txt", &["+Alpha", &format!("+{LOD}"), "+Beta"]);
        list("plugins.txt", &["FalloutNV.esm"]);
        list("loadorder.txt", &["FalloutNV.esm"]);
        f
    }

    fn path(&self, p: &str) -> PathBuf {
        self.root.path().join(p)
    }

    fn s(&self, p: &str) -> String {
        self.path(p).to_string_lossy().into_owned()
    }

    fn raul(&self, args: &[&str]) {
        let args: Vec<String> = args.iter().map(|a| (*a).to_owned()).collect();
        let out = ProcessExec::new(self.path("raul")).run(&args).unwrap();
        assert_eq!(out.code, Some(0), "{args:?}: {}", out.stderr);
    }

    /// The Profile's `modlist.txt` entries, highest priority first.
    fn modlist(&self) -> Vec<String> {
        std::fs::read_to_string(self.path("storage/instance/profiles/Default/modlist.txt"))
            .unwrap()
            .lines()
            .filter(|l| !l.is_empty() && !l.starts_with('#'))
            .map(str::to_owned)
            .collect()
    }

    fn app(&self) -> Harness<'static, App> {
        let exec = ProcessExec::new(self.path("raul")).with_grace(Duration::from_secs(5));
        let app = App::new(Jobs::new(Arc::new(exec)));
        let mut h = Harness::builder()
            .with_size([1280.0, 800.0])
            .build_eframe(|cc| {
                raul_gui::set_up(&cc.egui_ctx);
                app
            });
        settle(&mut h);
        h.get_all_by_label(msg::PAGE_MODS).next().unwrap().click();
        settle(&mut h);
        h
    }
}

/// Runs frames until the jobs the page starts have ended and it has taken their answers.
fn settle(h: &mut Harness<'static, App>) {
    for _ in 0..6 {
        h.run_steps(8);
        assert!(h.state_mut().wait_for_jobs(Duration::from_secs(60)));
    }
    h.run_steps(8);
}

fn status(h: &mut Harness<'static, App>) -> Option<String> {
    h.state_mut().shell_mut().status.clone()
}

#[test]
fn the_page_lists_changes_and_removes_mods_and_leaves_the_generated_lod_mod_to_the_lod_page() {
    let f = Fixture::new();
    let mut h = f.app();
    assert!(
        h.query_by_label("3 Mods, 3 enabled").is_some(),
        "the header counts them"
    );
    assert_eq!(
        h.query_all_by_label(TAG_GENERATED).count(),
        1,
        "only the LOD Mod is tagged"
    );

    // Turn Beta off from its detail, then on again: reversible, so nothing asks.
    h.get_by_label("Beta").click();
    h.run_steps(4);
    h.get_by_label(DISABLE).click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(DISABLED_STATUS));
    assert_eq!(f.modlist()[2], "-Beta");
    h.get_by_label(ENABLE).click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(ENABLED_STATUS));
    assert_eq!(f.modlist()[2], "+Beta");

    // Move Beta up one place: it passes the LOD Mod.
    h.get_by_label(MOVE_UP).click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(MOVED_STATUS));
    assert_eq!(
        f.modlist(),
        ["+Alpha".to_owned(), "+Beta".to_owned(), format!("+{LOD}")]
    );

    // The generated LOD Mod: no Remove, one line why, and Regenerate opens the LOD page.
    h.get_by_label(LOD).click();
    h.run_steps(4);
    assert!(
        h.query_by_label(REMOVE).is_none(),
        "a generated Mod is not removed here"
    );
    assert!(h.query_by_label(GENERATED_NOTE).is_some());
    h.get_by_label(REGENERATE).click();
    h.run_steps(4);
    assert_eq!(h.state().view(), View::Page(PageId::Lod));
    h.get_all_by_label(msg::PAGE_MODS).next().unwrap().click();
    settle(&mut h);

    // Remove asks once; Cancel keeps the Mod, Remove takes it out.
    h.get_by_label("Alpha").click();
    h.run_steps(4);
    h.get_by_label(REMOVE).click();
    h.run_steps(4);
    assert!(h.state().dialogs().is_open(), "Remove asks first");
    h.get_by_label(msg::CANCEL).click();
    settle(&mut h);
    assert!(
        f.path("storage/instance/mods/Alpha").is_dir(),
        "Cancel removes nothing"
    );
    h.get_by_label(REMOVE).click();
    h.run_steps(4);
    h.get_all_by_label(REMOVE_ACTION).last().unwrap().click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(REMOVED_STATUS));
    assert!(!f.path("storage/instance/mods/Alpha").exists());
    assert_eq!(f.modlist(), ["+Beta".to_owned(), format!("+{LOD}")]);
    assert!(
        h.query_by_label("2 Mods, 2 enabled").is_some(),
        "the list is read again"
    );
}
