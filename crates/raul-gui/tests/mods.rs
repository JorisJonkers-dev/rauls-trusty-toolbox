//! The Mods page end to end through the release `raul` on a synthetic Instance: it lists the Mods in priority order,
//! turns one off and on, moves one, removes one after asking, and gives the generated LOD Mod its own treatment
//! (tagged, Regenerate opens the LOD page, no Remove).
#![cfg(unix)]

use egui_kittest::Harness;
use egui_kittest::kittest::Queryable;
use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, write_file};
use raul_core::context::Context;
use raul_gui::catalogue as msg;
use raul_gui::jobs::Jobs;
use raul_gui::pages::mods::{
    DELETE, DELETE_ACTION, DISABLE, DISABLED_STATUS, ENABLE, ENABLED_STATUS, GENERATED_NOTE,
    MOVE_UP, MOVED_STATUS, REGENERATE, REMOVE, REMOVE_ACTION, REMOVED_STATUS,
    REMOVED_WITH_LOD_STATUS, TAG_GENERATED, UNDO, UNDO_ENABLED, UNDO_NOTHING, UNDONE_STATUS,
};
use raul_gui::shell::App;
use raul_testkit::{covers, ids};
use raul_ui_model::pages::{PageId, View};
use raul_ui_service::{Exec, InProcessExec};
use std::path::PathBuf;
use std::sync::Arc;
use std::time::Duration;

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";
const LOD: &str = "Generated LOD (Default)";

struct Fixture {
    root: TempDir,
}

impl Fixture {
    /// An Instance whose Profile lists `Alpha`, the generated LOD Mod and `Beta`, in that order.
    fn new() -> Fixture {
        let f = Fixture {
            root: TempDir::new("gui-mods"),
        };
        let base = f.path("base");
        BaseBuilder::steam().write(&base);
        write_file(
            &base,
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        f.raul(&["config", "set", "storage.root", &f.s("storage")]);
        f.raul(&[
            "init",
            "--base",
            &f.s("base"),
            "--instance",
            &f.s("storage/instance"),
        ]);
        let instance = f.path("storage/instance");
        write_file(&instance, "mods/Alpha/readme.txt", b"alpha");
        write_file(&instance, "mods/Beta/readme.txt", b"beta");
        // What `raul lod generate` leaves: the Mod and the marker in its meta.ini.
        write_file(
            &instance,
            &format!("mods/{LOD}/lodsettings/sample.dlodsettings"),
            b"lod",
        );
        write_file(
            &instance,
            &format!("mods/{LOD}/meta.ini"),
            b"[General]\r\ngameName=newvegas\r\n[raulGeneratedLod]\r\ngenerated=true\r\nprofile=Default\r\nrequestDigest=sha256:00\r\nlodwrightVersion=0.3.0\r\n",
        );
        let list = |name: &str, lines: &[&str]| {
            let mut text = HEADER.to_owned();
            for l in lines {
                text.push_str(l);
                text.push_str("\r\n");
            }
            write_file(
                &instance,
                &format!("profiles/Default/{name}"),
                text.as_bytes(),
            );
        };
        list("modlist.txt", &["+Alpha", &format!("+{LOD}"), "+Beta"]);
        list("plugins.txt", &["FalloutNV.esm"]);
        list("loadorder.txt", &["FalloutNV.esm"]);
        f
    }

    /// The folders this fixture's runs use: its own configuration, and no run log, so nothing reaches the real home.
    fn context(&self) -> Context {
        Context::new()
            .with_config_folder(self.path("config"))
            .without_run_log()
    }

    /// The command line run in this process with this fixture's folders.
    fn exec(&self) -> InProcessExec {
        InProcessExec::with_context(self.context())
    }

    fn path(&self, p: &str) -> PathBuf {
        self.root.path().join(p)
    }

    fn s(&self, p: &str) -> String {
        self.path(p).to_string_lossy().into_owned()
    }

    fn raul(&self, args: &[&str]) {
        let args: Vec<String> = args.iter().map(|a| (*a).to_owned()).collect();
        let out = self.exec().run(&args).unwrap();
        assert_eq!(out.code, Some(0), "{args:?}: {}", out.stderr);
    }

    /// The Profile's `modlist.txt` entries, highest priority first.
    fn modlist(&self) -> Vec<String> {
        std::fs::read_to_string(self.path("storage/instance/profiles/Default/modlist.txt"))
            .unwrap()
            .lines()
            .filter(|l| !l.is_empty() && !l.starts_with('#'))
            .map(str::to_owned)
            .collect()
    }

    fn app(&self) -> Harness<'static, App> {
        let exec = self.exec();
        let app = App::new(Jobs::new(Arc::new(exec)).with_context(self.context()));
        let mut h = Harness::builder()
            .with_size([1280.0, 800.0])
            .build_eframe(|cc| {
                raul_gui::set_up(&cc.egui_ctx);
                app
            });
        settle(&mut h);
        h.get_all_by_label(msg::PAGE_MODS).next().unwrap().click();
        settle(&mut h);
        h
    }
}

/// Runs frames until the jobs the page starts have ended and it has taken their answers.
fn settle(h: &mut Harness<'static, App>) {
    for _ in 0..6 {
        h.run_steps(8);
        assert!(h.state_mut().wait_for_jobs(Duration::from_secs(60)));
    }
    h.run_steps(8);
}

fn status(h: &mut Harness<'static, App>) -> Option<String> {
    h.state_mut().shell_mut().status.clone()
}

#[test]
fn the_page_lists_changes_and_removes_mods_and_leaves_the_generated_lod_mod_to_the_lod_page() {
    covers(&[ids::gui::pages::MODS_PAGE]);
    let f = Fixture::new();
    let mut h = f.app();
    assert!(
        h.query_by_label("3 Mods, 3 enabled").is_some(),
        "the header counts them"
    );
    assert_eq!(
        h.query_all_by_label(TAG_GENERATED).count(),
        1,
        "only the LOD Mod is tagged"
    );

    // Turn Beta off from its detail, then on again: reversible, so nothing asks.
    h.get_by_label("Beta").click();
    h.run_steps(4);
    h.get_by_label(DISABLE).click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(DISABLED_STATUS));
    assert_eq!(f.modlist()[2], "-Beta");
    h.get_by_label(ENABLE).click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(ENABLED_STATUS));
    assert_eq!(f.modlist()[2], "+Beta");

    // Undo takes the last change back through the journal, says what it takes back first, and is off afterwards.
    assert!(
        h.query_by_label(&UNDO_ENABLED.replace("{name}", "Beta"))
            .is_some(),
        "the line says what Undo takes back"
    );
    h.get_by_label(UNDO).click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(UNDONE_STATUS));
    assert_eq!(f.modlist()[2], "-Beta", "the enable was taken back");
    assert!(
        h.query_by_label(UNDO_NOTHING).is_some(),
        "nothing is left to undo"
    );
    h.get_by_label(ENABLE).click();
    settle(&mut h);
    assert_eq!(f.modlist()[2], "+Beta");

    // Move Beta up one place: it passes the LOD Mod.
    h.get_by_label(MOVE_UP).click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(MOVED_STATUS));
    assert_eq!(
        f.modlist(),
        ["+Alpha".to_owned(), "+Beta".to_owned(), format!("+{LOD}")]
    );

    // The generated LOD Mod: no Remove, one line why, and Regenerate opens the LOD page.
    h.get_by_label(LOD).click();
    h.run_steps(4);
    assert!(
        h.query_by_label(REMOVE).is_none(),
        "a generated Mod is not removed here"
    );
    assert!(h.query_by_label(GENERATED_NOTE).is_some());
    h.get_by_label(REGENERATE).click();
    h.run_steps(4);
    assert_eq!(h.state().view(), View::Page(PageId::Lod));
    h.get_all_by_label(msg::PAGE_MODS).next().unwrap().click();
    settle(&mut h);

    // Remove asks once; Cancel keeps the Mod, Remove takes it out.
    h.get_by_label("Alpha").click();
    h.run_steps(4);
    h.get_by_label(REMOVE).click();
    h.run_steps(4);
    assert!(h.state().dialogs().is_open(), "Remove asks first");
    h.get_by_label(msg::CANCEL).click();
    settle(&mut h);
    assert!(
        f.path("storage/instance/mods/Alpha").is_dir(),
        "Cancel removes nothing"
    );
    h.get_by_label(REMOVE).click();
    h.run_steps(4);
    h.get_all_by_label(REMOVE_ACTION).last().unwrap().click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(REMOVED_STATUS));
    assert!(!f.path("storage/instance/mods/Alpha").exists());
    assert_eq!(f.modlist(), ["+Beta".to_owned(), format!("+{LOD}")]);
    assert!(
        h.query_by_label("2 Mods, 2 enabled").is_some(),
        "the list is read again"
    );

    // Delete on the generated LOD Mod asks once, then takes it out the same way (issue 417).
    h.get_by_label(LOD).click();
    h.run_steps(4);
    h.get_by_label(DELETE).click();
    h.run_steps(4);
    assert!(h.state().dialogs().is_open(), "Delete asks first");
    h.get_all_by_label(DELETE_ACTION).last().unwrap().click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(REMOVED_STATUS));
    assert_eq!(f.modlist(), ["+Beta".to_owned()]);
    assert!(!f.path(&format!("storage/instance/mods/{LOD}")).exists());
}

/// The Profile of a packed LOD: the Mod `Tale of Two Wastelands` holds the game's first master, and the stub Plugin
/// of the generated LOD names it as its master.
fn packed_lod(f: &Fixture) {
    let instance = f.path("storage/instance");
    write_file(
        &instance,
        "mods/Tale of Two Wastelands/FalloutNV.esm",
        &PluginBuilder::master().build(),
    );
    write_file(
        &instance,
        &format!("mods/{LOD}/Lodwright LOD.esp"),
        &PluginBuilder::new().requires("FalloutNV.esm").build(),
    );
    let list = |name: &str, lines: &[&str]| {
        let mut text = HEADER.to_owned();
        for l in lines {
            text.push_str(l);
            text.push_str("\r\n");
        }
        write_file(
            &instance,
            &format!("profiles/Default/{name}"),
            text.as_bytes(),
        );
    };
    list(
        "modlist.txt",
        &["+Alpha", &format!("+{LOD}"), "+Tale of Two Wastelands"],
    );
    list("plugins.txt", &["FalloutNV.esm", "Lodwright LOD.esp"]);
    list("loadorder.txt", &["FalloutNV.esm", "Lodwright LOD.esp"]);
    f.raul(&["stage", "--instance", &f.s("storage/instance")]);
}

#[test]
fn removing_the_mod_that_the_packed_lod_needs_takes_the_generated_lod_out_with_it_and_undo_brings_the_mod_back()
 {
    let f = Fixture::new();
    packed_lod(&f);
    let mut h = f.app();
    h.get_by_label("Tale of Two Wastelands").click();
    h.run_steps(4);
    h.get_by_label(REMOVE).click();
    h.run_steps(4);
    h.get_all_by_label(REMOVE_ACTION).last().unwrap().click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(REMOVED_WITH_LOD_STATUS));
    assert_eq!(f.modlist(), ["+Alpha".to_owned()], "both Mods are gone");
    assert!(
        !f.path("storage/instance/mods/Tale of Two Wastelands")
            .exists()
    );
    assert!(!f.path(&format!("storage/instance/mods/{LOD}")).exists());
    assert!(
        h.query_all_by_label_contains("--force").next().is_none(),
        "no command-line flag in the window"
    );
    // Undo takes the last change back: the Mod is there again.
    h.get_by_label(UNDO).click();
    settle(&mut h);
    assert_eq!(status(&mut h).as_deref(), Some(UNDONE_STATUS));
    assert!(f.modlist().contains(&"+Tale of Two Wastelands".to_owned()));
    assert!(
        f.path("storage/instance/mods/Tale of Two Wastelands/FalloutNV.esm")
            .is_file()
    );
}

#[test]
fn removing_a_mod_that_a_plain_mod_needs_is_refused_in_plain_words_with_no_flag() {
    let f = Fixture::new();
    packed_lod(&f);
    // A Mod of the player's own needs the same master: the generated LOD is not the only one in the way.
    let instance = f.path("storage/instance");
    write_file(
        &instance,
        "mods/Patch/Patch.esp",
        &PluginBuilder::new().requires("FalloutNV.esm").build(),
    );
    for name in ["plugins.txt", "loadorder.txt"] {
        let path = instance.join("profiles/Default").join(name);
        let mut text = std::fs::read_to_string(&path).unwrap();
        text.push_str("Patch.esp\r\n");
        std::fs::write(path, text).unwrap();
    }
    let path = instance.join("profiles/Default/modlist.txt");
    let mut text = std::fs::read_to_string(&path).unwrap();
    text.push_str("+Patch\r\n");
    std::fs::write(path, text).unwrap();
    f.raul(&["stage", "--instance", &f.s("storage/instance")]);
    let mut h = f.app();
    h.get_by_label("Tale of Two Wastelands").click();
    h.run_steps(4);
    h.get_by_label(REMOVE).click();
    h.run_steps(4);
    h.get_all_by_label(REMOVE_ACTION).last().unwrap().click();
    settle(&mut h);
    assert!(
        f.path("storage/instance/mods/Tale of Two Wastelands")
            .is_dir(),
        "nothing was removed"
    );
    assert!(
        f.path(&format!("storage/instance/mods/{LOD}")).is_dir(),
        "the generated LOD stays"
    );
    assert!(
        h.query_all_by_label_contains("Patch.esp").next().is_some(),
        "the window names what is in the way"
    );
    assert!(
        h.query_all_by_label_contains("--force").next().is_none(),
        "no flag in the text"
    );
    assert!(
        h.query_all_by_label_contains("Turn those Mods off or remove them first")
            .next()
            .is_some()
    );
}
