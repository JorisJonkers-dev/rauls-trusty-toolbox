//! The window's jobs run the command line in this process (ADR-0016): `Jobs::real()` calls `raul_cli::run` through
//! `InProcessExec`, and no `raul` program is started. The setup commands and the jobs below run against a synthetic
//! Instance, and their results are read from the job table, as the window reads them.
//!
//! The proof that no process is started: a process runner would re-run this test binary as `raul`, so no test here
//! could pass through one. Nothing here writes a wrapper script or names a process runner.
#![cfg(unix)]

use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, write_file};
use raul_gui::jobs::Jobs;
use raul_ui_model::job::JobId;
use raul_ui_service::registry::Action;
use raul_ui_service::{Exec, InProcessExec};
use std::path::PathBuf;
use std::time::Duration;

const MASTERLIST: &str = "plugins:\n  - name: 'Other\\.esp'\n    msg:\n      - {type: warn, content: 'A synthetic warning'}\n";
const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

/// How long a job may take before the test fails. A job that does not end in this time is a failure, not a hang.
const JOB_TIMEOUT: Duration = Duration::from_secs(120);

struct Fixture {
    root: TempDir,
}

impl Fixture {
    fn new() -> Fixture {
        let f = Fixture {
            root: TempDir::new("gui-in-process"),
        };
        let base = f.path("base");
        BaseBuilder::steam().write(&base);
        write_file(
            &base,
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        std::fs::write(f.path("masterlist.yaml"), MASTERLIST).unwrap();
        f.run(&[
            "init",
            "--base",
            &f.s("base"),
            "--instance",
            &f.s("storage/instance"),
        ]);
        let instance = f.path("storage/instance");
        write_file(
            &instance,
            "mods/Patch/Patch.esp",
            &PluginBuilder::new().requires("Base.esp").build(),
        );
        write_file(
            &instance,
            "mods/Core/Base.esp",
            &PluginBuilder::new().build(),
        );
        write_file(
            &instance,
            "mods/Other/Other.esp",
            &PluginBuilder::new().build(),
        );
        let list = |name: &str, lines: &[&str]| {
            let mut text = HEADER.to_owned();
            for l in lines {
                text.push_str(l);
                text.push_str("\r\n");
            }
            write_file(
                &instance,
                &format!("profiles/Default/{name}"),
                text.as_bytes(),
            );
        };
        list("modlist.txt", &["+Patch", "+Core", "+Other"]);
        // The patch is listed before its master: the sort moves it.
        list(
            "plugins.txt",
            &["FalloutNV.esm", "Patch.esp", "Base.esp", "Other.esp"],
        );
        list(
            "loadorder.txt",
            &["FalloutNV.esm", "Patch.esp", "Base.esp", "Other.esp"],
        );
        f.run(&["stage", "--instance", &f.s("storage/instance")]);
        f
    }

    fn path(&self, p: &str) -> PathBuf {
        self.root.path().join(p)
    }

    fn s(&self, p: &str) -> String {
        self.path(p).to_string_lossy().into_owned()
    }

    /// Runs a setup command in this process, as the window's runner would, and checks that it went through.
    #[allow(clippy::unused_self)]
    fn run(&self, args: &[&str]) {
        let args: Vec<String> = args.iter().map(|a| (*a).to_owned()).collect();
        let out = InProcessExec::new().run(&args).unwrap();
        assert_eq!(out.code, Some(0), "{args:?}: {}", out.stderr);
    }

    fn load_order(&self) -> Vec<u8> {
        std::fs::read(self.path("storage/instance/profiles/Default/loadorder.txt")).unwrap()
    }
}

/// The names of the plugins, in the order a sort proposal lists them.
fn proposed_names(order: &serde_json::Value) -> Vec<String> {
    order
        .as_array()
        .expect("`order` is an array")
        .iter()
        .map(|slot| {
            slot["name"]
                .as_str()
                .expect("each slot has a name")
                .to_owned()
        })
        .collect()
}

fn position(names: &[String], name: &str) -> usize {
    names
        .iter()
        .position(|n| n == name)
        .unwrap_or_else(|| panic!("{name} is not in {names:?}"))
}

#[test]
fn a_sort_through_the_real_jobs_runs_in_process() {
    let f = Fixture::new();
    let before = f.load_order();
    let mut jobs = Jobs::real();
    let id: JobId = jobs
        .start(
            Action::Sort,
            vec![
                "--instance".into(),
                f.s("storage/instance"),
                "--masterlist".into(),
                f.s("masterlist.yaml"),
            ],
            false,
        )
        .unwrap();
    assert!(
        jobs.wait_all(JOB_TIMEOUT),
        "the sort job did not end within {JOB_TIMEOUT:?}"
    );
    jobs.poll();
    let out = jobs.output(id).expect("the sort job has an output");
    assert_eq!(out.code, Some(0), "stderr: {}", out.stderr);
    let proposal: serde_json::Value = serde_json::from_str(&out.stdout)
        .unwrap_or_else(|e| panic!("stdout is not JSON ({e}): {}", out.stdout));
    let names = proposed_names(&proposal["order"]);
    assert!(
        position(&names, "Base.esp") < position(&names, "Patch.esp"),
        "the proposal puts the master first: {names:?}"
    );
    assert_eq!(f.load_order(), before, "a preview writes nothing");
}

#[test]
fn a_chained_job_and_a_write_also_run_in_process() {
    let f = Fixture::new();
    let mut jobs = Jobs::real();
    let id = jobs
        .start(
            Action::Sort,
            vec![
                "--instance".into(),
                f.s("storage/instance"),
                "--masterlist".into(),
                f.s("masterlist.yaml"),
                "--apply".into(),
            ],
            true,
        )
        .unwrap();
    assert!(
        jobs.wait_all(JOB_TIMEOUT),
        "the applying sort did not end within {JOB_TIMEOUT:?}"
    );
    jobs.poll();
    let out = jobs.output(id).expect("the applying sort has an output");
    assert_eq!(out.code, Some(0), "stderr: {}", out.stderr);
    let text = String::from_utf8(f.load_order()).unwrap();
    assert!(
        text.find("Base.esp").unwrap() < text.find("Patch.esp").unwrap(),
        "the applied order puts the master first: {text}"
    );
}
