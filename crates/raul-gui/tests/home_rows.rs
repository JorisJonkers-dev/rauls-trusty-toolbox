//! Home's rows follow the Instance in the same session: a job that finishes while another page is open (the TTW
//! install, a LOD run) shows when the person comes back, without a restart (#454, gate pass 6). The Instance is a real
//! one, read by the window's own jobs.
#![cfg(unix)]

use egui_kittest::Harness;
use egui_kittest::kittest::Queryable;
use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, write_file};
use raul_core::context::Context;
use raul_gui::jobs::Jobs;
use raul_gui::shell::App;
use raul_ui_model::pages::{PageId, View};
use raul_ui_service::{Exec, InProcessExec};
use std::sync::Arc;
use std::time::Duration;

const TTW_ROW: &str = "Installed";
const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

struct Fixture {
    root: TempDir,
}

impl Fixture {
    fn new() -> Fixture {
        let f = Fixture {
            root: TempDir::new("gui-home-rows"),
        };
        let base = f.root.path().join("base");
        BaseBuilder::steam().write(&base);
        write_file(
            &base,
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        f.raul(&["config", "set", "storage.root", &f.s("storage")]);
        f.raul(&["config", "set", "game.newvegas", &f.s("base")]);
        f.raul(&[
            "init",
            "--base",
            &f.s("base"),
            "--instance",
            &f.s("storage/instance"),
        ]);
        f
    }

    fn context(&self) -> Context {
        Context::new()
            .with_config_folder(self.root.path().join("config"))
            .without_run_log()
    }

    fn s(&self, p: &str) -> String {
        self.root.path().join(p).to_string_lossy().into_owned()
    }

    fn raul(&self, args: &[&str]) {
        let args: Vec<String> = args.iter().map(|a| (*a).to_owned()).collect();
        let out = InProcessExec::with_context(self.context())
            .run(&args)
            .unwrap();
        assert_eq!(out.code, Some(0), "{args:?}: {}", out.stderr);
    }

    /// The Tale of Two Wastelands Mod arrives in the Instance, as the install leaves it.
    fn install_ttw(&self) {
        let instance = self.root.path().join("storage/instance");
        write_file(
            &instance,
            "mods/Tale of Two Wastelands/TaleOfTwoWastelands.esm",
            &PluginBuilder::master().build(),
        );
        write_file(
            &instance,
            "profiles/Default/modlist.txt",
            format!("{HEADER}+Tale of Two Wastelands\r\n").as_bytes(),
        );
    }
}

fn settle(h: &mut Harness<'static, App>) {
    for _ in 0..4 {
        h.run_steps(8);
        assert!(h.state_mut().wait_for_jobs(Duration::from_secs(60)));
    }
    h.run_steps(8);
}

#[test]
fn the_ttw_row_follows_the_instance_when_a_job_finished_on_another_page() {
    let f = Fixture::new();
    let jobs =
        Jobs::new(Arc::new(InProcessExec::with_context(f.context()))).with_context(f.context());
    let app = App::new(jobs);
    let mut h = Harness::builder()
        .with_size([1280.0, 800.0])
        .build_eframe(|cc| {
            raul_gui::set_up(&cc.egui_ctx);
            app
        });
    settle(&mut h);
    assert_eq!(h.state().view(), View::Page(PageId::Home));
    assert!(
        h.query_by_label(TTW_ROW).is_none(),
        "no TTW Mod in the list yet"
    );
    // The install finishes while the Mods page is open.
    h.state_mut().open(View::Page(PageId::Mods));
    settle(&mut h);
    f.install_ttw();
    h.state_mut().open(View::Page(PageId::Home));
    settle(&mut h);
    assert!(
        h.query_by_label(TTW_ROW).is_some(),
        "Home reads the mod list again on the way back"
    );
}
