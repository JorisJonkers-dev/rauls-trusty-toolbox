//! The Load order page end to end: it lists the plugins, sorts with a preview, applies and undoes through the
//! release `raul` on a synthetic Instance, and Undo restores the plugin lists byte for byte. The masterlist is a
//! file written here: a wrapper passes it where the page asks for the pinned one, so nothing is fetched.
#![cfg(unix)]

use egui_kittest::Harness;
use egui_kittest::kittest::Queryable;
use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, write_file, write_script};
use raul_gui::catalogue as msg;
use raul_gui::jobs::Jobs;
use raul_gui::pages::load_order::{APPLIED_STATUS, SORT, UNDO, UNDONE_STATUS};
use raul_gui::shell::App;
use raul_ui_service::{CancelHandle, Exec, Output, ProcessExec};
use std::path::PathBuf;
use std::sync::{Arc, Mutex};
use std::time::Duration;

const MASTERLIST: &str = "plugins:\n  - name: 'Other\\.esp'\n    msg:\n      - {type: warn, content: 'A synthetic warning'}\n";
const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

struct Fixture {
    root: TempDir,
}

impl Fixture {
    fn new() -> Fixture {
        let f = Fixture {
            root: TempDir::new("gui-load-order"),
        };
        let base = f.path("base");
        BaseBuilder::steam().write(&base);
        write_file(
            &base,
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        std::fs::write(f.path("masterlist.yaml"), MASTERLIST).unwrap();
        // `raul` with this fixture's configuration and state, and the masterlist file instead of the pinned one.
        write_script(
            f.root.path(),
            "raul",
            &format!(
                "export RAUL_CONFIG_DIR='{c}' NVMOD_STATE_DIR='{s}'\nfor a do shift; if [ \"$a\" = --fetch-masterlist ]; then set -- \"$@\" --masterlist '{m}'; else set -- \"$@\" \"$a\"; fi; done\nexec '{raul}' \"$@\"",
                c = f.path("config").display(),
                s = f.path("state").display(),
                m = f.path("masterlist.yaml").display(),
                raul = env!("CARGO_BIN_EXE_raul"),
            ),
        );
        let storage = f.s("storage");
        f.raul(&["config", "set", "storage.root", &storage]);
        let instance = f.path("storage/instance");
        f.raul(&[
            "init",
            "--base",
            &f.s("base"),
            "--instance",
            &f.s("storage/instance"),
        ]);
        write_file(
            &instance,
            "mods/Patch/Patch.esp",
            &PluginBuilder::new().requires("Base.esp").build(),
        );
        write_file(
            &instance,
            "mods/Core/Base.esp",
            &PluginBuilder::new().build(),
        );
        write_file(
            &instance,
            "mods/Other/Other.esp",
            &PluginBuilder::new().build(),
        );
        let list = |name: &str, lines: &[&str]| {
            let mut text = HEADER.to_owned();
            for l in lines {
                text.push_str(l);
                text.push_str("\r\n");
            }
            write_file(
                &instance,
                &format!("profiles/Default/{name}"),
                text.as_bytes(),
            );
        };
        list("modlist.txt", &["+Patch", "+Core", "+Other"]);
        // The patch is listed before its master: the sort moves it.
        list(
            "plugins.txt",
            &["FalloutNV.esm", "Patch.esp", "Base.esp", "Other.esp"],
        );
        list(
            "loadorder.txt",
            &["FalloutNV.esm", "Patch.esp", "Base.esp", "Other.esp"],
        );
        f.raul(&["stage", "--instance", &f.s("storage/instance")]);
        f
    }

    fn path(&self, p: &str) -> PathBuf {
        self.root.path().join(p)
    }

    fn s(&self, p: &str) -> String {
        self.path(p).to_string_lossy().into_owned()
    }

    fn raul(&self, args: &[&str]) {
        let args: Vec<String> = args.iter().map(|a| (*a).to_owned()).collect();
        let out = ProcessExec::new(self.path("raul")).run(&args).unwrap();
        assert_eq!(out.code, Some(0), "{args:?}: {}", out.stderr);
    }

    fn lists(&self) -> (Vec<u8>, Vec<u8>) {
        let dir = self.path("storage/instance/profiles/Default");
        (
            std::fs::read(dir.join("plugins.txt")).unwrap(),
            std::fs::read(dir.join("loadorder.txt")).unwrap(),
        )
    }
}

/// The real runner, noting the command word of every command line it is asked to run.
struct Recording {
    inner: ProcessExec,
    words: Arc<Mutex<Vec<String>>>,
}

impl Recording {
    fn note(&self, args: &[String]) {
        self.words
            .lock()
            .unwrap()
            .push(args.first().cloned().unwrap_or_default());
    }
}

impl Exec for Recording {
    fn run(&self, args: &[String]) -> Result<Output, String> {
        self.note(args);
        self.inner.run(args)
    }

    fn run_streaming(
        &self,
        args: &[String],
        on_line: &mut dyn FnMut(&str),
    ) -> Result<Output, String> {
        self.note(args);
        self.inner.run_streaming(args, on_line)
    }

    fn run_cancellable(
        &self,
        args: &[String],
        on_line: &mut dyn FnMut(&str),
        cancel: &CancelHandle,
    ) -> Result<Output, String> {
        self.note(args);
        self.inner.run_cancellable(args, on_line, cancel)
    }
}

/// Runs frames until the jobs the page starts have ended and it has taken their answers.
fn settle(h: &mut Harness<'static, App>) {
    for _ in 0..6 {
        h.run_steps(8);
        assert!(h.state_mut().wait_for_jobs(Duration::from_secs(60)));
    }
    h.run_steps(8);
}

#[test]
fn sort_preview_apply_then_undo_restores_the_lists_byte_for_byte() {
    let f = Fixture::new();
    let before = f.lists();
    let words = Arc::new(Mutex::new(Vec::new()));
    let exec = Recording {
        inner: ProcessExec::new(f.path("raul")).with_grace(Duration::from_secs(5)),
        words: Arc::clone(&words),
    };
    let app = App::new(Jobs::new(Arc::new(exec)));
    let mut h = Harness::builder()
        .with_size([1280.0, 800.0])
        .build_eframe(|cc| {
            raul_gui::set_up(&cc.egui_ctx);
            app
        });
    settle(&mut h);
    h.get_all_by_label(msg::PAGE_LOAD_ORDER)
        .next()
        .unwrap()
        .click();
    settle(&mut h);
    assert!(h.query_by_label("Patch.esp").is_some(), "the list is shown");

    h.get_by_label(SORT).click();
    settle(&mut h);
    assert_eq!(f.lists(), before, "a preview writes nothing");
    h.get_by_label_contains("Apply 1 move").click();
    settle(&mut h);
    assert_eq!(
        h.state_mut().shell_mut().status.as_deref(),
        Some(APPLIED_STATUS)
    );
    let applied = f.lists();
    assert_ne!(applied.1, before.1, "the sorted order is written");
    let text = String::from_utf8(applied.1).unwrap();
    assert!(
        text.find("Base.esp").unwrap() < text.find("Patch.esp").unwrap(),
        "{text}"
    );

    h.get_by_label(UNDO).click();
    settle(&mut h);
    assert_eq!(
        h.state_mut().shell_mut().status.as_deref(),
        Some(UNDONE_STATUS)
    );
    assert_eq!(f.lists(), before, "Undo restores both lists byte for byte");
    assert!(h.query_by_label(UNDO).is_none(), "nothing left to undo");
    let words = words.lock().unwrap();
    assert!(
        words.iter().any(|w| w == "sort"),
        "the sort is a command line: {words:?}"
    );
    assert!(
        !words.iter().any(|w| w == "rollback"),
        "Undo runs in process, as a typed job, not as a command line: {words:?}"
    );
}
