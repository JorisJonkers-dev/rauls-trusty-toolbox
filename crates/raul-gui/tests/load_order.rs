//! The Load order page end to end: it lists the plugins, sorts with a preview, applies and undoes through the
//! release `raul` on a synthetic Instance, and Undo restores the plugin lists byte for byte. The masterlist is a
//! file written here: the fixture's command passes it where the page asks for the pinned one, so nothing is fetched.
#![cfg(unix)]

use eframe::egui;
use egui_kittest::Harness;
use egui_kittest::kittest::Queryable;
use nvmod_testkit::{BaseBuilder, PluginBuilder, TempDir, write_file};
use raul_core::context::Context;
use raul_gui::catalogue as msg;
use raul_gui::jobs::Jobs;
use raul_gui::pages::load_order::{
    APPLIED_STATUS, DISABLED_STATUS, ENABLED_STATUS, SORT, SWITCH_ACTION, UNDO, UNDONE_STATUS,
};
use raul_gui::shell::App;
use raul_ui_service::{CancelHandle, Exec, InProcessExec, Output};
use std::path::PathBuf;
use std::sync::{Arc, Mutex};
use std::time::Duration;

const MASTERLIST: &str = "plugins:\n  - name: 'Other\\.esp'\n    msg:\n      - {type: warn, content: 'A synthetic warning'}\n";
const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

struct Fixture {
    root: TempDir,
}

impl Fixture {
    fn new() -> Fixture {
        let f = Fixture {
            root: TempDir::new("gui-load-order"),
        };
        let base = f.path("base");
        BaseBuilder::steam().write(&base);
        write_file(
            &base,
            "Data/FalloutNV.esm",
            &PluginBuilder::master().build(),
        );
        std::fs::write(f.path("masterlist.yaml"), MASTERLIST).unwrap();
        let storage = f.s("storage");
        f.raul(&["config", "set", "storage.root", &storage]);
        let instance = f.path("storage/instance");
        f.raul(&[
            "init",
            "--base",
            &f.s("base"),
            "--instance",
            &f.s("storage/instance"),
        ]);
        write_file(
            &instance,
            "mods/Patch/Patch.esp",
            &PluginBuilder::new().requires("Base.esp").build(),
        );
        write_file(
            &instance,
            "mods/Core/Base.esp",
            &PluginBuilder::new().build(),
        );
        write_file(
            &instance,
            "mods/Other/Other.esp",
            &PluginBuilder::new().build(),
        );
        let list = |name: &str, lines: &[&str]| {
            let mut text = HEADER.to_owned();
            for l in lines {
                text.push_str(l);
                text.push_str("\r\n");
            }
            write_file(
                &instance,
                &format!("profiles/Default/{name}"),
                text.as_bytes(),
            );
        };
        list("modlist.txt", &["+Patch", "+Core", "+Other"]);
        // The patch is listed before its master: the sort moves it.
        list(
            "plugins.txt",
            &["FalloutNV.esm", "Patch.esp", "Base.esp", "Other.esp"],
        );
        list(
            "loadorder.txt",
            &["FalloutNV.esm", "Patch.esp", "Base.esp", "Other.esp"],
        );
        f.raul(&["stage", "--instance", &f.s("storage/instance")]);
        f
    }

    /// The folders this fixture's runs use: its own configuration, and no run log, so nothing reaches the real home.
    fn context(&self) -> Context {
        Context::new()
            .with_config_folder(self.path("config"))
            .without_run_log()
    }

    /// The command line run in this process with this fixture's folders, and the masterlist file where the pages ask for the pinned one.
    fn exec(&self) -> InProcessExec {
        InProcessExec::with_context(self.context()).with_argument_replaced(
            "--fetch-masterlist",
            &["--masterlist", &self.s("masterlist.yaml")],
        )
    }

    fn path(&self, p: &str) -> PathBuf {
        self.root.path().join(p)
    }

    fn s(&self, p: &str) -> String {
        self.path(p).to_string_lossy().into_owned()
    }

    fn raul(&self, args: &[&str]) {
        let args: Vec<String> = args.iter().map(|a| (*a).to_owned()).collect();
        let out = self.exec().run(&args).unwrap();
        assert_eq!(out.code, Some(0), "{args:?}: {}", out.stderr);
    }

    fn lists(&self) -> (Vec<u8>, Vec<u8>) {
        let dir = self.path("storage/instance/profiles/Default");
        (
            std::fs::read(dir.join("plugins.txt")).unwrap(),
            std::fs::read(dir.join("loadorder.txt")).unwrap(),
        )
    }
}

/// The real runner, noting the command word of every command line it is asked to run.
struct Recording {
    inner: InProcessExec,
    words: Arc<Mutex<Vec<String>>>,
}

impl Recording {
    fn note(&self, args: &[String]) {
        self.words
            .lock()
            .unwrap()
            .push(args.first().cloned().unwrap_or_default());
    }
}

impl Exec for Recording {
    fn run(&self, args: &[String]) -> Result<Output, String> {
        self.note(args);
        self.inner.run(args)
    }

    fn run_streaming(
        &self,
        args: &[String],
        on_line: &mut dyn FnMut(&str),
    ) -> Result<Output, String> {
        self.note(args);
        self.inner.run_streaming(args, on_line)
    }

    fn run_cancellable(
        &self,
        args: &[String],
        on_line: &mut dyn FnMut(&str),
        cancel: &CancelHandle,
    ) -> Result<Output, String> {
        self.note(args);
        self.inner.run_cancellable(args, on_line, cancel)
    }
}

/// Runs frames until the jobs the page starts have ended and it has taken their answers.
fn settle(h: &mut Harness<'static, App>) {
    for _ in 0..6 {
        h.run_steps(8);
        assert!(h.state_mut().wait_for_jobs(Duration::from_secs(60)));
    }
    h.run_steps(8);
}

#[test]
fn sort_preview_apply_then_undo_restores_the_lists_byte_for_byte() {
    let f = Fixture::new();
    let before = f.lists();
    let words = Arc::new(Mutex::new(Vec::new()));
    let exec = Recording {
        inner: f.exec(),
        words: Arc::clone(&words),
    };
    // The sort stays a command line here: the fixture's command swaps the pinned masterlist for a file, which a direct sort
    // (it fetches the pinned one itself) would not go through.
    let jobs = Jobs::new(Arc::new(exec))
        .with_context(f.context())
        .scripted(&["sort-preview", "sort-apply"]);
    let app = App::new(jobs);
    let mut h = Harness::builder()
        .with_size([1280.0, 800.0])
        .build_eframe(|cc| {
            raul_gui::set_up(&cc.egui_ctx);
            app
        });
    settle(&mut h);
    h.get_all_by_label(msg::PAGE_LOAD_ORDER)
        .next()
        .unwrap()
        .click();
    settle(&mut h);
    assert!(h.query_by_label("Patch.esp").is_some(), "the list is shown");

    h.get_by_label(SORT).click();
    settle(&mut h);
    assert_eq!(f.lists(), before, "a preview writes nothing");
    h.get_by_label_contains("Apply 2 moves").click();
    settle(&mut h);
    assert_eq!(
        h.state_mut().shell_mut().status.as_deref(),
        Some(APPLIED_STATUS)
    );
    let applied = f.lists();
    assert_ne!(applied.1, before.1, "the sorted order is written");
    let text = String::from_utf8(applied.1).unwrap();
    assert!(
        text.find("Base.esp").unwrap() < text.find("Patch.esp").unwrap(),
        "{text}"
    );

    h.get_by_label(UNDO).click();
    settle(&mut h);
    assert_eq!(
        h.state_mut().shell_mut().status.as_deref(),
        Some(UNDONE_STATUS)
    );
    assert_eq!(f.lists(), before, "Undo restores both lists byte for byte");
    assert!(h.query_by_label(UNDO).is_none(), "nothing left to undo");
    let words = words.lock().unwrap();
    assert!(
        words.iter().any(|w| w == "sort"),
        "the sort is a command line: {words:?}"
    );
    assert!(
        !words.iter().any(|w| w == "rollback"),
        "Undo runs in process, as a typed job, not as a command line: {words:?}"
    );
}

/// The stub of a packed LOD, last in both lists, as the generator leaves it.
fn add_stub(f: &Fixture) {
    let instance = f.path("storage/instance");
    write_file(
        &instance,
        "mods/Lodwright LOD/Lodwright LOD.esp",
        &PluginBuilder::new().requires("FalloutNV.esm").build(),
    );
    for name in ["plugins.txt", "loadorder.txt"] {
        let path = instance.join("profiles/Default").join(name);
        let mut text = std::fs::read_to_string(&path).unwrap();
        text.push_str("Lodwright LOD.esp\r\n");
        std::fs::write(path, text).unwrap();
    }
    let modlist = instance.join("profiles/Default/modlist.txt");
    let mut text = std::fs::read_to_string(&modlist).unwrap();
    text.push_str("+Lodwright LOD\r\n");
    std::fs::write(modlist, text).unwrap();
    f.raul(&["stage", "--instance", &f.s("storage/instance")]);
}

fn active(f: &Fixture) -> Vec<String> {
    String::from_utf8(f.lists().0)
        .unwrap()
        .lines()
        .map(|l| l.trim_start_matches('*').to_owned())
        .collect()
}

#[test]
fn a_plugin_is_turned_off_and_on_from_its_switch_and_the_stub_of_a_packed_lod_asks_first() {
    let f = Fixture::new();
    add_stub(&f);
    let jobs = Jobs::new(Arc::new(f.exec())).with_context(f.context());
    let app = App::new(jobs);
    let mut h = Harness::builder()
        .with_size([1280.0, 800.0])
        .build_eframe(|cc| {
            raul_gui::set_up(&cc.egui_ctx);
            app
        });
    settle(&mut h);
    h.get_all_by_label(msg::PAGE_LOAD_ORDER)
        .next()
        .unwrap()
        .click();
    settle(&mut h);
    let switches =
        |h: &Harness<'static, App>| h.get_all_by_role(egui::accesskit::Role::CheckBox).count();
    assert_eq!(switches(&h), 5, "one switch for each plugin");

    // Rows: FalloutNV.esm, Patch.esp, Base.esp, Other.esp, Lodwright LOD.esp.
    let click = |h: &mut Harness<'static, App>, row: usize| {
        h.get_all_by_role(egui::accesskit::Role::CheckBox)
            .nth(row)
            .unwrap()
            .click();
    };
    click(&mut h, 3);
    settle(&mut h);
    assert!(
        !active(&f).contains(&"Other.esp".to_owned()),
        "{:?}",
        active(&f)
    );
    assert_eq!(
        h.state_mut().shell_mut().status.as_deref(),
        Some(DISABLED_STATUS.replace("{name}", "Other.esp").as_str())
    );
    assert!(h.query_by_label("5 plugins, 4 active").is_some());
    click(&mut h, 3);
    settle(&mut h);
    assert!(active(&f).contains(&"Other.esp".to_owned()));
    assert_eq!(
        h.state_mut().shell_mut().status.as_deref(),
        Some(ENABLED_STATUS.replace("{name}", "Other.esp").as_str())
    );

    // The stub: the question first, and Cancel changes nothing.
    let before = f.lists();
    click(&mut h, 4);
    h.run_steps(4);
    assert!(
        h.state().dialogs().is_open(),
        "turning the stub off asks first"
    );
    h.get_by_label(msg::CANCEL).click();
    settle(&mut h);
    assert_eq!(f.lists(), before, "Cancel writes nothing");
    click(&mut h, 4);
    h.run_steps(4);
    h.get_all_by_label(SWITCH_ACTION).last().unwrap().click();
    settle(&mut h);
    assert!(!active(&f).contains(&"Lodwright LOD.esp".to_owned()));
    assert!(
        active(&f).contains(&"Other.esp".to_owned()),
        "only the stub went off"
    );
    // Turning it on needs no question.
    click(&mut h, 4);
    settle(&mut h);
    assert!(active(&f).contains(&"Lodwright LOD.esp".to_owned()));
    assert!(!h.state().dialogs().is_open());
}

#[test]
fn turning_on_a_plugin_whose_master_is_off_says_what_to_turn_on_first_and_names_no_flag() {
    let f = Fixture::new();
    let jobs = Jobs::new(Arc::new(f.exec())).with_context(f.context());
    let app = App::new(jobs);
    let mut h = Harness::builder()
        .with_size([1280.0, 800.0])
        .build_eframe(|cc| {
            raul_gui::set_up(&cc.egui_ctx);
            app
        });
    settle(&mut h);
    h.get_all_by_label(msg::PAGE_LOAD_ORDER)
        .next()
        .unwrap()
        .click();
    settle(&mut h);
    let click = |h: &mut Harness<'static, App>, row: usize| {
        h.get_all_by_role(egui::accesskit::Role::CheckBox)
            .nth(row)
            .unwrap()
            .click();
    };
    // Rows: FalloutNV.esm, Patch.esp, Base.esp, Other.esp. Patch needs Base: turn both off, then Patch on again.
    click(&mut h, 1);
    settle(&mut h);
    click(&mut h, 2);
    settle(&mut h);
    click(&mut h, 1);
    settle(&mut h);
    assert!(
        h.query_all_by_label_contains("Turn those plugins on first")
            .next()
            .is_some(),
        "the window says what to do"
    );
    assert!(
        h.query_all_by_label_contains("--with-masters")
            .next()
            .is_none(),
        "no flag in the text"
    );
    assert!(
        !active(&f).contains(&"Patch.esp".to_owned()),
        "nothing was turned on"
    );
}
