//! Every command the pages start (`raul_ui_service::registry::COMMANDS`), run by the release `raul` against a
//! synthetic Instance: each is understood (no usage error, no unknown command), and each that takes `--json`
//! answers with JSON. The configuration and nvmod's state go to the test's own folders.
// Starts the built binary, which is not a tool call.
#![allow(clippy::disallowed_methods)]

use nvmod_testkit::{BaseBuilder, TempDir};
use raul_ui_service::registry::{Action, COMMANDS, Command};
use std::path::Path;
use std::process::Command as Process;

/// The exit code of a command line that was not understood.
const USAGE: i32 = 5;

struct Fixture {
    root: TempDir,
}

impl Fixture {
    fn new() -> Fixture {
        let root = TempDir::new("registry-fixture");
        BaseBuilder::steam().write(&root.path().join("base"));
        std::fs::create_dir_all(root.path().join("config")).unwrap();
        std::fs::create_dir_all(root.path().join("state")).unwrap();
        std::fs::write(root.path().join("masterlist.yaml"), "plugins: []\n").unwrap();
        let f = Fixture { root };
        let out = f.raul(&[
            "init",
            "--base",
            &f.path("base"),
            "--instance",
            &f.path("instance"),
        ]);
        assert_eq!(out.0, 0, "init: {}", out.2);
        // A Default profile with only the game's master, as a fresh setup leaves it.
        let profile = f.root.path().join("instance/profiles/Default");
        std::fs::create_dir_all(&profile).unwrap();
        let header = "# This file was automatically generated by Mod Organizer.\r\n";
        std::fs::write(profile.join("modlist.txt"), header).unwrap();
        for list in ["plugins.txt", "loadorder.txt"] {
            std::fs::write(profile.join(list), format!("{header}FalloutNV.esm\r\n")).unwrap();
        }
        let staged = f.raul(&["stage", "--instance", &f.path("instance")]);
        assert_eq!(staged.0, 0, "stage: {}", staged.2);
        // One Mod for the Mods page's commands to enable, disable, move and remove.
        let created = f.raul(&["mods", "create", "Alpha", "--instance", &f.path("instance")]);
        assert_eq!(created.0, 0, "mods create: {}", created.2);
        f
    }

    fn path(&self, name: &str) -> String {
        self.root.path().join(name).to_string_lossy().into_owned()
    }

    fn raul(&self, args: &[&str]) -> (i32, String, String) {
        let out = Process::new(env!("CARGO_BIN_EXE_raul"))
            .args(args)
            .env("RAUL_CONFIG_DIR", self.root.path().join("config"))
            .env("NVMOD_STATE_DIR", self.root.path().join("state"))
            // A home of its own, so no nv-rs build of the machine running the tests is found.
            .env("HOME", self.root.path().join("home"))
            .env("USERPROFILE", self.root.path().join("home"))
            .output()
            .expect("run raul");
        (
            out.status.code().unwrap_or(-1),
            String::from_utf8_lossy(&out.stdout).into_owned(),
            String::from_utf8_lossy(&out.stderr).into_owned(),
        )
    }

    /// The values and flags a page would pass for `command`, on this fixture.
    fn rest(&self, command: &Command) -> Vec<String> {
        let instance = self.path("instance");
        let words: Vec<&str> = match (command.action, command.words) {
            (Action::Config, ["get" | "unset"]) => vec!["game.newvegas"],
            (Action::Config, ["set"]) => vec!["game.newvegas", "BASE"],
            // In the registry's order: the Mods page turns the fixture's Mod off and on, moves it and removes it.
            (Action::Mods, ["enable" | "disable" | "remove"]) => {
                vec!["Alpha", "--instance", &instance]
            }
            (Action::Mods, ["reorder"]) => {
                vec!["Alpha", "--position", "1", "--instance", &instance]
            }
            // In the registry's order: set one LOD option, unset another one (nothing to change), Restore defaults
            // removes the first and keeps a restore point, and Undo puts it back; each succeeds.
            (Action::Lod, ["settings", "set"]) => {
                vec!["output.trees", "false", "--instance", &instance]
            }
            (Action::Lod, ["settings", "unset"]) => vec!["output.water", "--instance", &instance],
            (Action::InstallNvRs, _) => {
                vec!["--instance", &instance]
            }
            (Action::Init, _) => vec!["--base", "BASE", "--instance", "NEW"],
            // The target the fixture's Instance has already: nothing changes.
            (Action::Target, _) => vec!["vanilla", "--instance", &instance],
            (Action::Sort, _) if command.flags.contains(&"--apply") && command.writes => {
                vec![
                    "--instance",
                    &instance,
                    "--masterlist",
                    "MASTERLIST",
                    "--apply",
                ]
            }
            (Action::Sort, _) => vec!["--instance", &instance, "--masterlist", "MASTERLIST"],
            (Action::Ttw, _) => vec!["--instance", &instance, "--dry-run"],
            // An archive that is not there: the command understands the words and refuses it. The install of a
            // real archive is covered by the service test with a synthetic one.
            (Action::InstallMod, _) => vec!["missing.zip", "--instance", &instance, "--dry-run"],
            (Action::Detect | Action::Space, _) => vec!["--folder", "BASE"],
            // The default profile of an Instance that already has one: nothing changes.
            (Action::Profile, _) => vec!["--name", "Default", "--instance", &instance],
            // A dry run: the launch plan is printed and nothing is started.
            (Action::Run, _) => vec!["nv-rs", "--instance", &instance, "--dry-run"],
            (Action::Config | Action::Version | Action::Update | Action::Tools, _) => vec![],
            _ => vec!["--instance", &instance],
        };
        let mut rest: Vec<String> = words
            .into_iter()
            .map(|w| match w {
                "BASE" => self.path("base"),
                "NEW" => self.path("second"),
                "MASTERLIST" => self.path("masterlist.yaml"),
                other => other.to_owned(),
            })
            .collect();
        if command.action.takes_json() {
            rest.push("--json".into());
        }
        rest
    }
}

fn understood(line: &str, (code, out, err): &(i32, String, String), json: bool) {
    assert_ne!(*code, USAGE, "`{line}` was not understood: {err}");
    assert!(!err.contains("unknown command"), "`{line}`: {err}");
    if json && *code == 0 {
        for l in out.lines().filter(|l| !l.trim().is_empty()) {
            assert!(
                serde_json::from_str::<serde_json::Value>(l).is_ok()
                    || serde_json::from_str::<serde_json::Value>(out).is_ok(),
                "`{line}` printed a line that is not JSON: {l}"
            );
        }
    }
}

/// The exit code each command gives on the fixture: the engine install finds no engine packaged next to the test program and is refused (2), TTW
/// with no Fallout 3 folder is refused (2), LOD generation in the fixture, whose game master has no terrain, fails in lodwright (4), verify finds no engine (3), a run with no engine is refused (2),
/// the Doctor finds the fixture's missing pieces (1), the rest succeed; the rollback undoes the sort that ran before it.
fn expected(command: &Command) -> i32 {
    match command.action {
        // TTW and a run: no folder, and no engine installed in the fixture, so even a dry run is refused. The engine
        // install finds no packaged engine next to the test program.
        // The fixture's Instance has its default profile already: a second one is refused.
        // `run --stop` only asks for a stop, so it succeeds with nothing running.
        Action::Run if command.words.first() == Some(&"--stop") => 0,
        Action::InstallNvRs | Action::Ttw | Action::Run | Action::Profile | Action::InstallMod => 2,
        // lodwright is linked in: the fixture's plugin defines no worldspace with terrain, so the generation fails.
        Action::Lod if command.words.first() == Some(&"generate") => 4,
        Action::Doctor => 1,
        // No engine is installed in the fixture, so the install does not verify.
        Action::Verify => 3,
        _ => 0,
    }
}

#[test]
fn every_page_command_runs_against_a_fixture() {
    let f = Fixture::new();
    let mut ran = 0;
    for command in COMMANDS.iter().filter(|c| c.awaits.is_none()) {
        let args = command.args(f.rest(command));
        let words: Vec<&str> = std::iter::once(command.action.command())
            .chain(args.iter().map(String::as_str))
            .collect();
        let result = f.raul(&words);
        understood(&command.line(), &result, command.action.takes_json());
        if command.action == Action::Update {
            // It asks the release list on the network: what it answers depends on the machine, not on the command.
            ran += 1;
            continue;
        }
        assert_eq!(
            result.0,
            expected(command),
            "`{}`: {}",
            command.line(),
            result.2
        );
        ran += 1;
    }
    assert!(ran >= 13, "{ran}");
}

#[test]
fn config_set_then_get_reads_it_back() {
    let f = Fixture::new();
    let base = f.path("base");
    assert_eq!(
        f.raul(&["config", "set", "game.newvegas", &base, "--json"])
            .0,
        0
    );
    let (code, out, _) = f.raul(&["config", "get", "game.newvegas", "--json"]);
    assert_eq!(code, 0);
    assert!(out.contains(&base.replace('\\', "\\\\")), "{out}");
    assert!(
        Path::new(&f.path("config"))
            .read_dir()
            .unwrap()
            .next()
            .is_some()
    );
}
