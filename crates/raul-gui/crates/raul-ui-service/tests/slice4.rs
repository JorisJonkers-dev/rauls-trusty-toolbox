struct InProcess;

impl Exec for InProcess {
    fn run(&self, args: &[String]) -> Result<Output, String> {
        // Journal ids are the millisecond and the process id; separate runs of the program differ in the second,
        // runs in this one process need a millisecond between them.
        std::thread::sleep(Duration::from_millis(3));
        let (mut out, mut err) = (Vec::new(), Vec::new());
        let code = raul_cli::run(args, &mut out, &mut err);
        Ok(Output {
            code: Some(i64::from(code)),
            stdout: String::from_utf8_lossy(&out).into_owned(),
            stderr: String::from_utf8_lossy(&err).into_owned(),
        })
    }
}

fn s(p: &Path) -> String {
    p.to_str().unwrap().to_owned()
}

fn nvmod(args: &[&str]) -> Output {
    let args: Vec<String> = args.iter().map(|a| (*a).to_owned()).collect();
    InProcess.run(&args).unwrap()
}

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

/// An Instance with the Mods A, B and C installed (C has the highest priority).
struct Rig {
    base: TempDir,
    dir: TempDir,
    work: TempDir,
}

impl Rig {
    fn new() -> Self {
        let rig = Self {
            base: TempDir::new("s4-base"),
            dir: TempDir::new("s4-inst"),
            work: TempDir::new("s4-work"),
        };
        BaseBuilder::steam().write(rig.base.path());
        let out = nvmod(&[
            "init",
            "--base",
            &s(rig.base.path()),
            "--instance",
            &s(&rig.root()),
        ]);
        assert_eq!(out.code, Some(0), "{}", out.stderr);
        for p in ["modlist.txt", "plugins.txt", "loadorder.txt"] {
            let body = if p == "modlist.txt" {
                ""
            } else {
                "FalloutNV.esm\r\n"
            };
            write_file(
                &rig.root(),
                &format!("profiles/Default/{p}"),
                format!("{HEADER}{body}").as_bytes(),
            );
        }
        let svc = CliService::new(InProcess);
        for name in ["A", "B", "C"] {
            let zip = rig.work.path().join(format!("{name}.zip"));
            ZipBuilder::new()
                .file("data.txt", name.as_bytes())
                .write(&zip);
            svc.install_mod(&InstallRequest {
                archive: s(&zip),
                instance: s(&rig.root()),
                profile: None,
                name: Some(name.to_owned()),
                dry_run: false,
                answers: None,
            })
            .unwrap();
        }
        rig
    }

    fn root(&self) -> PathBuf {
        self.dir.path().join("i")
    }

    fn ctx(&self) -> ModsContext {
        ModsContext {
            instance: s(&self.root()),
            profile: None,
        }
    }

    fn rows(&self) -> Vec<ModEntry> {
        let out = nvmod(&["mods", "list", "--instance", &s(&self.root()), "--json"]);
        assert_eq!(out.code, Some(0), "{}", out.stderr);
        let v: serde_json::Value = serde_json::from_str(&out.stdout).unwrap();
        serde_json::from_value::<Vec<ModEntry>>(v["mods"].clone()).unwrap()
    }

    fn screen(&self) -> ModsScreen {
        let mut screen = ModsScreen::new();
        screen.loaded(self.rows().iter().map(ModRow::from).collect());
        screen
    }

    fn modlist(&self) -> String {
        std::fs::read_to_string(self.root().join("profiles/Default/modlist.txt")).unwrap()
    }
}

fn names(rows: &[ModEntry]) -> Vec<(&str, &str)> {
    rows.iter()
        .map(|r| (r.name.as_str(), r.state.as_str()))
        .collect()
}

#[test]
fn staged_mods_edits_preview_with_a_dry_run_then_apply_and_undo() {
    let rig = Rig::new();
    let svc = CliService::new(InProcess);
    let mut screen = rig.screen();
    assert_eq!(
        names(&rig.rows()),
        [("C", "enabled"), ("B", "enabled"), ("A", "enabled")]
    );
    screen.set_enabled("B", false).unwrap();
    screen.move_to("A", 0).unwrap();
    let before = rig.modlist();

    let preview = preview_mods(&screen, &svc, &rig.ctx()).unwrap();
    assert!(preview.exact);
    assert_eq!(preview.steps.len(), 2, "one disable and one move");
    assert!(
        preview
            .steps
            .iter()
            .all(|(_, r)| r.dry_run && r.journal.is_none())
    );
    assert_eq!(preview.changed(), ["B", "A"]);
    assert_eq!(rig.modlist(), before, "a preview writes nothing");

    let done = apply_mods(&mut screen, &svc, &rig.ctx());
    assert_eq!((done.applied, done.total, done.undone), (2, 2, 0));
    assert!(done.error.is_none());
    assert!(
        !screen.is_dirty(),
        "the screen was reloaded from the result"
    );
    assert_eq!(
        names(&rig.rows()),
        [("A", "enabled"), ("C", "enabled"), ("B", "disabled")]
    );
    assert_eq!(
        screen
            .visible()
            .iter()
            .map(|r| (r.name.as_str(), r.enabled))
            .collect::<Vec<_>>(),
        [("A", true), ("C", true), ("B", false)]
    );

    // Each step has its own journal: two undos bring the list back.
    for _ in 0..2 {
        svc.rollback(&RollbackRequest {
            instance: s(&rig.root()),
        })
        .unwrap();
    }
    assert_eq!(rig.modlist(), before);
}

#[test]
fn a_refused_step_undoes_the_ones_before_it_and_keeps_the_edits_staged() {
    let rig = Rig::new();
    let svc = CliService::new(InProcess);
    let before = rig.modlist();
    // A screen that read an older list: its second step names a Mod the profile no longer has.
    let mut stale = ModsScreen::new();
    stale.loaded(vec![
        ModRow {
            name: "B".into(),
            enabled: true,
        },
        ModRow {
            name: "Ghost".into(),
            enabled: true,
        },
    ]);
    stale.set_enabled("B", false).unwrap();
    stale.move_to("Ghost", 0).unwrap();
    let done = apply_mods(&mut stale, &svc, &rig.ctx());
    assert_eq!((done.applied, done.undone), (0, 1));
    let error = done.error.unwrap();
    assert_eq!(error.exit, ExitClass::Refused);
    assert!(error.what.contains("Ghost"), "{}", error.what);
    assert!(error.effect.contains("undone"), "{}", error.effect);
    assert!(stale.is_dirty(), "the edits stay staged");
    assert_eq!(rig.modlist(), before, "the disable of B was taken back");
}

#[test]
fn a_typed_setup_request_runs_as_a_dry_run_and_a_resume_is_refused_without_a_state_file() {
    let rig = Rig::new();
    let masterlist = rig.work.path().join("masterlist.yaml");
    std::fs::write(&masterlist, "globals: []\nplugins: []\n").unwrap();
    let target = rig.work.path().join("new-instance");
    let svc = CliService::new(InProcess);
    let mut request = SetupRequest::fresh(&s(&target), &s(rig.base.path()), &s(&masterlist));
    request.skip_nv_rs = true;
    request.dry_run = true;
    let report = svc.setup(&request).unwrap();
    assert!(report.dry_run && !report.resume);
    assert!(report.steps.iter().any(|st| st.name == "init"));
    assert!(!target.exists(), "a dry run writes nothing");

    let e = svc
        .setup(&SetupRequest::resume(&s(&target)))
        .unwrap_err()
        .view_error();
    assert_eq!(e.exit, ExitClass::Refused);
    assert!(e.what.contains("no unfinished setup"), "{}", e.what);
    assert!(
        e.repro.is_none(),
        "the setup runs in process: there is no command line to repeat"
    );
}

/// An executor that counts the commands it is asked to run (and runs none).
struct CountingExec(std::sync::Arc<std::sync::atomic::AtomicUsize>);

impl Exec for CountingExec {
    fn run(&self, _args: &[String]) -> Result<Output, String> {
        self.0.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
        Err("no command may be run".to_owned())
    }
}

/// The setup wizard's request runs the setup job in process: nothing is started and no command is run.
#[test]
fn a_typed_setup_request_starts_no_process_and_runs_no_command() {
    let rig = Rig::new();
    let masterlist = rig.work.path().join("masterlist.yaml");
    std::fs::write(&masterlist, "globals: []\nplugins: []\n").unwrap();
    let target = rig.work.path().join("new-instance");
    write_file(rig.base.path(), "nvse_1_4.dll", &PeBuilder::dll().build());
    write_file(
        rig.base.path(),
        "Data/FalloutNV.esm",
        &PluginBuilder::master().build(),
    );
    let ran = std::sync::Arc::new(std::sync::atomic::AtomicUsize::new(0));
    let svc = CliService::new(CountingExec(std::sync::Arc::clone(&ran)));
    let mut request = SetupRequest::fresh(&s(&target), &s(rig.base.path()), &s(&masterlist));
    request.skip_nv_rs = true;
    let report = svc.setup(&request).unwrap();
    assert!(!report.dry_run && report.steps.iter().any(|st| st.name == "verify"));
    assert!(
        target.join("nvmod-instance.json").is_file(),
        "the Instance was made"
    );
    assert!(
        target.join(".raul/setup-journal.json").is_file(),
        "each step is in the journal"
    );
    assert_eq!(
        ran.load(std::sync::atomic::Ordering::SeqCst),
        0,
        "no command was run"
    );
}

fn setup_plan() -> &'static str {
    r#"echo '{"seq":1,"event":"plan","dry_run":false,"resume":false,"instance":"/i","steps":[{"step":"init","description":"Make the Instance"}]}'
echo '{"seq":2,"event":"step","step":"init","status":"started","index":1,"total":1,"description":"Make the Instance"}'"#
}

/// Runs `body` as the `nvmod` program, cancels the job once it printed its plan and returns what happened.
fn cancelled_run(body: &str, grace: Duration) -> (JobTable, Output, Duration) {
    let dir = TempDir::new("s4-script");
    let program = write_script(dir.path(), "nvmod", body);
    let svc = CliService::new(ProcessExec::new(program).with_grace(grace));
    let spec = JobSpec::new(JobId(1), Action::Setup, vec![]).writing();
    assert!(spec.cancellable);
    let cancel = CancelHandle::new();
    let mut table = JobTable::default();
    let begun = Instant::now();
    let mut asked = false;
    let out = svc
        .run_job_cancellable(
            &spec,
            &mut |event| {
                table.apply(event);
                if !asked && table.get(JobId(1)).is_some() {
                    asked = true;
                    cancel_job(&mut table, JobId(1), &cancel).unwrap();
                }
            },
            &cancel,
        )
        .unwrap();
    (table, out, begun.elapsed())
}

#[test]
fn a_command_that_rolls_itself_back_when_asked_to_stop_ends_as_rolled_back() {
    let body = format!(
        "{}\ntrap 'echo {{\\\"seq\\\":3,\\\"event\\\":\\\"finished\\\",\\\"status\\\":\\\"failed\\\",\\\"exit_code\\\":4,\\\"rolled_back\\\":true,\\\"resumable\\\":false}}; exit 4' TERM\nwhile :; do sleep 0.05; done",
        setup_plan()
    );
    let (table, out, took) = cancelled_run(&body, Duration::from_secs(5));
    assert_eq!(out.code, Some(4));
    let job = table.get(JobId(1)).unwrap();
    assert_eq!(job.state, JobState::Finished(Outcome::RolledBack));
    assert_eq!(job.exit, Some(ExitClass::StepFailedRolledBack));
    assert!(took < Duration::from_secs(4), "{took:?}");
    assert!(table.writing().is_none());
}

#[test]
fn a_command_that_dies_of_the_stop_ends_as_failed_with_the_doctor_advice() {
    let body = format!("{}\nsleep 30", setup_plan());
    let (table, out, took) = cancelled_run(&body, Duration::from_secs(5));
    assert_eq!(out.code, None, "ended by a signal");
    let job = table.get(JobId(1)).unwrap();
    assert_eq!(job.state, JobState::Finished(Outcome::Failed));
    assert!(
        job.log_tail.iter().any(|l| l.contains("run the Doctor")),
        "{:?}",
        job.log_tail
    );
    assert!(took < Duration::from_secs(4), "{took:?}");
}

#[test]
fn a_command_that_ignores_the_stop_is_forced_after_the_grace_period() {
    let body = format!(
        "{}\ntrap '' TERM\nwhile :; do sleep 0.05; done",
        setup_plan()
    );
    let (table, out, took) = cancelled_run(&body, Duration::from_millis(300));
    assert_eq!(out.code, None);
    assert_eq!(
        table.get(JobId(1)).unwrap().state,
        JobState::Finished(Outcome::Failed)
    );
    assert!(
        took >= Duration::from_millis(300) && took < Duration::from_secs(5),
        "{took:?}"
    );
}

#[test]
fn a_cancel_before_the_start_runs_nothing() {
    let dir = TempDir::new("s4-script");
    let program = write_script(dir.path(), "nvmod", "touch ran");
    let svc = CliService::new(ProcessExec::new(program));
    let cancel = CancelHandle::new();
    cancel.request();
    let mut table = JobTable::default();
    let spec = JobSpec::new(JobId(1), Action::InstallMod, vec![]).writing();
    svc.run_job_in_cancellable(&spec, &mut table, &cancel)
        .unwrap();
    assert_eq!(
        table.get(JobId(1)).unwrap().state,
        JobState::Finished(Outcome::Cancelled)
    );
    assert!(!Path::new("ran").exists());
}

/// The service keeps no state of its own: every answer comes from the disk as it is after the last write, whoever
/// made that write.
#[test]
fn every_read_after_a_write_comes_from_the_disk_and_nothing_is_cached() {
    let rig = Rig::new();
    let svc = CliService::new(InProcess);
    let change = |step: ModStep, dry_run: bool| {
        svc.mods_change(&ModsRequest {
            instance: s(&rig.root()),
            profile: None,
            step,
            dry_run,
        })
        .unwrap()
    };
    let done = change(ModStep::Disable(vec!["B".into()]), false);
    assert_eq!(
        names(&done.mods),
        [("C", "enabled"), ("B", "disabled"), ("A", "enabled")]
    );
    let mut screen = rig.screen();
    assert_eq!(
        screen
            .visible()
            .iter()
            .map(|r| r.enabled)
            .collect::<Vec<_>>(),
        [true, false, true],
        "the screen loads what the write left"
    );
    // Another program changes the Instance behind the service's back.
    let out = nvmod(&["mods", "enable", "B", "--instance", &s(&rig.root())]);
    assert_eq!(out.code, Some(0), "{}", out.stderr);
    let plan = change(ModStep::Disable(vec!["A".into()]), true);
    assert_eq!(
        names(&plan.mods),
        [("C", "enabled"), ("B", "enabled"), ("A", "disabled")],
        "the next answer starts from the disk, not from the service's last answer"
    );
    screen.loaded(rig.rows().iter().map(ModRow::from).collect());
    assert!(
        screen.visible().iter().all(|r| r.enabled),
        "a dry run wrote nothing"
    );
}
