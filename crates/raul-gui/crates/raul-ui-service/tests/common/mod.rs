//! A synthetic Instance for the tests of the direct jobs. No game data is used.
#![allow(dead_code)]

use nvmod_api::install::{InstallOutput, InstallRequest};
use nvmod_api::{CancelToken, NoProgress, Outcome};
use nvmod_testkit::{BaseBuilder, TempDir, ZipBuilder, write_file};
use std::path::{Path, PathBuf};

/// A path as text.
pub fn s(p: &Path) -> String {
    p.to_str().unwrap().to_owned()
}

/// An Instance made by nvmod's own `init` job, with an empty profile `Default`.
pub struct Instance {
    _base: TempDir,
    dir: TempDir,
    pub work: TempDir,
}

impl Instance {
    pub fn new() -> Self {
        let base = TempDir::new("rb-base");
        BaseBuilder::steam().write(base.path());
        let dir = TempDir::new("rb-inst");
        let root = dir.path().join("i");
        nvmod_api::init::create(
            &nvmod_api::init::CreateRequest {
                instance: root.clone(),
                base: base.path().to_owned(),
            },
            &mut NoProgress,
            &CancelToken::new(),
        )
        .unwrap();
        let header = "# This file was automatically generated by Mod Organizer.\r\n";
        write_file(&root, "profiles/Default/modlist.txt", header.as_bytes());
        for file in ["plugins.txt", "loadorder.txt"] {
            write_file(
                &root,
                &format!("profiles/Default/{file}"),
                format!("{header}FalloutNV.esm\r\n").as_bytes(),
            );
        }
        Self {
            _base: base,
            dir,
            work: TempDir::new("rb-work"),
        }
    }

    pub fn root(&self) -> PathBuf {
        self.dir.path().join("i")
    }
}

/// Installs `Plain Mod` with nvmod's own install job, so there is a journal to undo.
pub fn install_plain(inst: &Instance) {
    let zip = inst.work.path().join("Plain.zip");
    ZipBuilder::new().file("P.esp", b"plugin").write(&zip);
    let request = InstallRequest {
        instance: inst.root(),
        profile: None,
        archive: zip,
        name: Some("Plain Mod".into()),
        dry_run: false,
        answers: None,
        max_extract_bytes: None,
        extract_limits: nvmod_api::install::LimitOverrides::default(),
        fomod_answers: None,
        on_conflict: nvmod_api::install::OnConflict::default(),
        placement: nvmod_api::install::Placement::Top,
    };
    match nvmod_api::install::install(&request, &mut NoProgress, &CancelToken::new()).unwrap() {
        Outcome::Done(InstallOutput::Installed(_)) => {}
        other => panic!("expected the Mod to install, got {other:?}"),
    }
}
