/// Runs `nvmod_cli::run` in this process.
struct InProcess;

impl Exec for InProcess {
    fn run(&self, args: &[String]) -> Result<Output, String> {
        let (mut out, mut err) = (Vec::new(), Vec::new());
        let code = nvmod_cli::run(args, &mut out, &mut err);
        Ok(Output {
            code: Some(i64::from(code)),
            stdout: String::from_utf8_lossy(&out).into_owned(),
            stderr: String::from_utf8_lossy(&err).into_owned(),
        })
    }
}

fn service() -> CliService<InProcess> {
    CliService::new(InProcess)
}

fn s(p: &std::path::Path) -> String {
    p.to_str().unwrap().to_owned()
}

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

fn profile(root: &std::path::Path, mods: &str, plugins: &str) {
    write_file(
        root,
        "profiles/Default/modlist.txt",
        format!("{HEADER}{mods}").as_bytes(),
    );
    write_file(
        root,
        "profiles/Default/plugins.txt",
        format!("{HEADER}{plugins}").as_bytes(),
    );
    write_file(
        root,
        "profiles/Default/loadorder.txt",
        format!("{HEADER}{plugins}").as_bytes(),
    );
}

/// An Instance made by `nvmod init`, with an empty profile `Default`.
struct Instance {
    _base: TempDir,
    dir: TempDir,
    work: TempDir,
}

impl Instance {
    fn new() -> Self {
        let base = TempDir::new("svc-base");
        BaseBuilder::steam().write(base.path());
        let dir = TempDir::new("svc-inst");
        let root = dir.path().join("i");
        let args: Vec<String> = ["init", "--base", &s(base.path()), "--instance", &s(&root)]
            .iter()
            .map(|a| (*a).to_owned())
            .collect();
        let out = InProcess.run(&args).unwrap();
        assert_eq!(out.code, Some(0), "{}", out.stderr);
        profile(&root, "", "FalloutNV.esm\r\n");
        Self {
            _base: base,
            dir,
            work: TempDir::new("svc-work"),
        }
    }

    fn root(&self) -> PathBuf {
        self.dir.path().join("i")
    }
}

#[test]
fn install_plans_asks_the_fomod_questions_then_installs() {
    let inst = Instance::new();
    let zip = inst.work.path().join("Ask.zip");
    ZipBuilder::new()
        .file(
            "fomod/ModuleConfig.xml",
            br#"<config><moduleName>Ask</moduleName>
  <installSteps order="Explicit"><installStep name="Options"><optionalFileGroups order="Explicit">
    <group name="Style" type="SelectExactlyOne"><plugins order="Explicit">
      <plugin name="Red"><description>red one</description><files><file source="red.txt" destination="style.txt"/></files>
        <typeDescriptor><type name="Optional"/></typeDescriptor></plugin>
      <plugin name="Blue"><files><file source="blue.txt" destination="style.txt"/></files>
        <typeDescriptor><type name="Optional"/></typeDescriptor></plugin>
    </plugins></group>
  </optionalFileGroups></installStep></installSteps></config>"#,
        )
        .file("red.txt", b"red")
        .file("blue.txt", b"blue")
        .write(&zip);
    let svc = service();
    let ctx = InstallContext {
        instance: s(&inst.root()),
        profile: None,
        name: None,
    };
    let mut w = InstallWizard::new();
    w.choose_archive(s(&zip)).unwrap();
    plan_install(&mut w, &svc, &ctx).unwrap();
    assert_eq!(w.flow.step(), Step::Input, "the FOMOD needs answers");
    let q = w.fomod().unwrap().current().unwrap().clone();
    assert_eq!(q.id, "Options/Style");
    assert_eq!(q.options[0].name, "Red");
    assert_eq!(q.options[0].description, "red one");
    assert!(
        !inst.root().join("mods/Ask").exists(),
        "the dry run wrote nothing"
    );

    w.fomod_mut().unwrap().answer(&q.id, &["Blue"]).unwrap();
    w.submit_answers().unwrap();
    plan_install(&mut w, &svc, &ctx).unwrap();
    assert_eq!(w.flow.step(), Step::Review);
    assert_eq!(w.planned_files(), ["style.txt"]);
    assert!(!inst.root().join("mods/Ask").exists());
    w.flow.mark_reviewed().unwrap();
    apply_install(&mut w, &svc, &ctx).unwrap();
    assert_eq!(w.flow.step(), Step::Done);
    assert_eq!(
        std::fs::read(inst.root().join("mods/Ask/style.txt")).unwrap(),
        b"blue"
    );
}

