fn service() -> CliService<InProcessExec> {
    CliService::new(InProcessExec::new())
}

fn s(p: &std::path::Path) -> String {
    p.to_str().unwrap().to_owned()
}

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

fn profile(root: &std::path::Path, mods: &str, plugins: &str) {
    write_file(
        root,
        "profiles/Default/modlist.txt",
        format!("{HEADER}{mods}").as_bytes(),
    );
    write_file(
        root,
        "profiles/Default/plugins.txt",
        format!("{HEADER}{plugins}").as_bytes(),
    );
    write_file(
        root,
        "profiles/Default/loadorder.txt",
        format!("{HEADER}{plugins}").as_bytes(),
    );
}

/// An Instance made by `raul init`, with an empty profile `Default`.
struct Instance {
    base: TempDir,
    dir: TempDir,
    work: TempDir,
}

impl Instance {
    fn new() -> Self {
        let base = TempDir::new("svc-base");
        BaseBuilder::steam().write(base.path());
        let dir = TempDir::new("svc-inst");
        let root = dir.path().join("i");
        let args: Vec<String> = ["init", "--base", &s(base.path()), "--instance", &s(&root)]
            .iter()
            .map(|a| (*a).to_owned())
            .collect();
        let out = InProcessExec::new().run(&args).unwrap();
        assert_eq!(out.code, Some(0), "{}", out.stderr);
        profile(&root, "", "FalloutNV.esm\r\n");
        Self {
            base,
            dir,
            work: TempDir::new("svc-work"),
        }
    }

    fn root(&self) -> PathBuf {
        self.dir.path().join("i")
    }
}

#[test]
fn install_plans_asks_the_fomod_questions_then_installs() {
    let inst = Instance::new();
    let zip = inst.work.path().join("Ask.zip");
    ZipBuilder::new()
        .file(
            "fomod/ModuleConfig.xml",
            br#"<config><moduleName>Ask</moduleName>
  <installSteps order="Explicit"><installStep name="Options"><optionalFileGroups order="Explicit">
    <group name="Style" type="SelectExactlyOne"><plugins order="Explicit">
      <plugin name="Red"><description>red one</description><files><file source="red.txt" destination="style.txt"/></files>
        <typeDescriptor><type name="Optional"/></typeDescriptor></plugin>
      <plugin name="Blue"><files><file source="blue.txt" destination="style.txt"/></files>
        <typeDescriptor><type name="Optional"/></typeDescriptor></plugin>
    </plugins></group>
  </optionalFileGroups></installStep></installSteps></config>"#,
        )
        .file("red.txt", b"red")
        .file("blue.txt", b"blue")
        .write(&zip);
    let svc = service();
    let ctx = InstallContext {
        instance: s(&inst.root()),
        profile: None,
        name: None,
    };
    let mut w = InstallWizard::new();
    w.choose_archive(s(&zip)).unwrap();
    plan_install(&mut w, &svc, &ctx).unwrap();
    assert_eq!(w.flow.step(), Step::Input, "the FOMOD needs answers");
    let q = w.fomod().unwrap().current().unwrap().clone();
    assert_eq!(q.id, "Options/Style");
    assert_eq!(q.options[0].name, "Red");
    assert_eq!(q.options[0].description, "red one");
    assert!(
        !inst.root().join("mods/Ask").exists(),
        "the dry run wrote nothing"
    );

    w.fomod_mut().unwrap().answer(&q.id, &["Blue"]).unwrap();
    w.submit_answers().unwrap();
    plan_install(&mut w, &svc, &ctx).unwrap();
    assert_eq!(w.flow.step(), Step::Review);
    assert_eq!(w.planned_files(), ["style.txt"]);
    assert!(!inst.root().join("mods/Ask").exists());
    w.flow.mark_reviewed().unwrap();
    apply_install(&mut w, &svc, &ctx).unwrap();
    assert_eq!(w.flow.step(), Step::Done);
    assert_eq!(
        std::fs::read(inst.root().join("mods/Ask/style.txt")).unwrap(),
        b"blue"
    );
}

#[test]
fn install_reports_and_refusals_are_read() {
    let inst = Instance::new();
    let zip = inst.work.path().join("Plain.zip");
    ZipBuilder::new().file("P.esp", b"plugin").write(&zip);
    let svc = service();
    let mut req = InstallRequest {
        archive: s(&zip),
        instance: s(&inst.root()),
        profile: None,
        name: Some("Plain Mod".into()),
        dry_run: false,
        answers: None,
    };
    let InstallResult::Report(r) = svc.install_mod(&req).unwrap() else {
        panic!("expected a report");
    };
    assert_eq!(r.mod_name, "Plain Mod");
    assert_eq!(r.plugins, ["P.esp"]);
    assert!(r.journal.is_some() && !r.dry_run);

    req.archive = s(&inst.work.path().join("missing.zip"));
    let ServiceError::Failed(e) = svc.install_mod(&req).unwrap_err() else {
        panic!("expected a failure");
    };
    assert_eq!(e.exit, ExitClass::Refused);
}

fn mo2(dir: &std::path::Path, loadorder: &[u8]) {
    write_file(
        dir,
        "ModOrganizer.ini",
        b"[General]\r\ngameName=TTW\r\nselected_profile=@ByteArray(Example Profile)\r\n",
    );
    write_file(dir, "mods/Example Mod/meshes/rock.nif", b"rock");
    write_file(dir, "mods/Example Mod/Example Mod.esp", b"esp");
    let p = "profiles/Example Profile";
    write_file(
        dir,
        &format!("{p}/modlist.txt"),
        format!("{HEADER}+Example Mod\r\n").as_bytes(),
    );
    write_file(
        dir,
        &format!("{p}/plugins.txt"),
        format!("{HEADER}FalloutNV.esm\r\nExample Mod.esp\r\n").as_bytes(),
    );
    write_file(dir, &format!("{p}/loadorder.txt"), loadorder);
}

#[test]
fn import_creates_an_instance_and_a_disagreement_comes_back_as_rows() {
    let base = TempDir::new("svc-imp-base");
    BaseBuilder::steam().write(base.path());
    let good = TempDir::new("svc-imp-good");
    mo2(
        good.path(),
        format!("{HEADER}FalloutNV.esm\r\nExample Mod.esp\r\n").as_bytes(),
    );
    let out = TempDir::new("svc-imp-out");
    let svc = service();
    let mut w = ImportWizard::new();
    w.set_mo2(s(good.path()));
    plan_import(&mut w).unwrap();
    w.flow.mark_reviewed().unwrap();
    let ctx = ImportContext {
        instance: s(&out.path().join("new")),
        base: s(base.path()),
    };
    apply_import(&mut w, &svc, &ctx).unwrap();
    assert_eq!(w.flow.step(), Step::Done);
    assert!(
        out.path()
            .join("new/mods/Example Mod/meshes/rock.nif")
            .is_file()
    );

    let bad = TempDir::new("svc-imp-bad");
    mo2(bad.path(), format!("{HEADER}FalloutNV.esm\r\n").as_bytes());
    let mut w = ImportWizard::new();
    w.set_mo2(s(bad.path()));
    plan_import(&mut w).unwrap();
    w.flow.mark_reviewed().unwrap();
    let ctx = ImportContext {
        instance: s(&out.path().join("never")),
        base: s(base.path()),
    };
    apply_import(&mut w, &svc, &ctx).unwrap();
    assert_eq!(w.flow.step(), Step::Review);
    assert_eq!(w.blockers().len(), 1, "{:?}", w.blockers());
    assert!(
        w.blockers()[0].text.starts_with("Example Mod.esp"),
        "{:?}",
        w.blockers()
    );
    assert!(!out.path().join("never").exists(), "nothing was written");
}

