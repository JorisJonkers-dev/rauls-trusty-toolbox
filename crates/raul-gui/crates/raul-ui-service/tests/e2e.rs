/// Builds the Staging tree of profile `Default`, which `sort` needs.
fn stage(inst: &Instance) {
    let args: Vec<String> = [
        "stage",
        "--instance",
        &s(&inst.root()),
        "--profile",
        "Default",
    ]
    .iter()
    .map(|a| (*a).to_owned())
    .collect();
    let out = InProcessExec::new().run(&args).unwrap();
    assert_eq!(out.code, Some(0), "{}", out.stderr);
}

