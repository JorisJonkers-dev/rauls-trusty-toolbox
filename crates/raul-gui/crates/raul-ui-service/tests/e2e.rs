#[test]
fn a_real_run_streams_its_events_into_the_job_table_as_they_are_printed() {
    let inst = Instance::new();
    let masterlist = inst.work.path().join("masterlist.yaml");
    std::fs::write(&masterlist, MASTERLIST).unwrap();
    // The setup command prints one event per line as it goes; a dry run needs no network and writes nothing.
    let target = inst.work.path().join("new-instance");
    let args: Vec<String> = [
        "--base",
        &s(inst.base.path()),
        "--instance",
        &s(&target),
        "--masterlist",
        &s(&masterlist),
        "--skip-nv-rs",
        "--dry-run",
    ]
    .iter()
    .map(|a| (*a).to_owned())
    .collect();
    let spec = JobSpec::new(JobId(1), Action::Setup, args).writing();
    let mut table = JobTable::default();
    let mut running_events = 0;
    let out = service()
        .run_job(&spec, &mut |event| {
            table.apply(event);
            if table
                .get(JobId(1))
                .is_some_and(|j| j.state == JobState::Running)
            {
                running_events += 1;
            }
        })
        .unwrap();
    assert_eq!(out.code, Some(0), "{}", out.stderr);
    // `Started` comes before the command prints anything, so more than one event with the job still running means
    // the command's own lines (the plan, the steps) arrived before it ended.
    assert!(
        running_events >= 2,
        "the command's lines arrived while it was still running: {running_events} event(s)"
    );
    assert!(table.writing().is_none(), "the Instance is free again");
    assert_eq!(
        table.get(JobId(1)).unwrap().state,
        JobState::Finished(Outcome::DryRun)
    );
    assert!(!target.exists(), "a dry run writes nothing");
}

#[test]
fn a_real_sort_run_as_a_job_ends_with_a_final_record() {
    let inst = Instance::new();
    let masterlist = inst.work.path().join("masterlist.yaml");
    std::fs::write(&masterlist, MASTERLIST).unwrap();
    stage(&inst);
    let req = SortRequest {
        instance: s(&inst.root()),
        masterlist: s(&masterlist),
        apply: true,
        ..SortRequest::default()
    };
    let mut table = JobTable::default();
    service()
        .run_job_in(
            &JobSpec::new(JobId(5), Action::Sort, req.args()).writing(),
            &mut table,
        )
        .unwrap();
    let job = table.get(JobId(5)).unwrap();
    assert_eq!(job.state, JobState::Finished(Outcome::Completed));
    assert_eq!(job.exit, Some(ExitClass::Ok));
    assert!(table.writing().is_none());
}

#[test]
fn conflicts_and_tree_are_typed_reports_and_a_missing_profile_is_a_failure() {
    use raul_ui_service::{ConflictsRequest, TreeRequest};
    let inst = Instance::new();
    let root = inst.root();
    profile(&root, "+A\r\n+B\r\n", "FalloutNV.esm\r\n");
    write_file(&root, "mods/A/Meshes/x.nif", b"a");
    write_file(&root, "mods/B/meshes/X.nif", b"b");
    write_file(&root, "mods/B/only.txt", b"b");
    let svc = service();
    let report = svc
        .conflicts(&ConflictsRequest {
            instance: s(&root),
            ..ConflictsRequest::default()
        })
        .unwrap();
    assert_eq!(report.conflicts.len(), 1);
    assert_eq!(report.conflicts[0].winner.name, "A");
    assert_eq!(report.conflicts[0].losers[0].path, "meshes/X.nif");
    assert!(
        report
            .mods
            .iter()
            .any(|m| m.name == "B" && !m.mixed && m.overwritten)
    );
    let tree = svc
        .tree(&TreeRequest {
            instance: s(&root),
            path: Some("meshes".to_owned()),
            ..TreeRequest::default()
        })
        .unwrap();
    assert_eq!(tree.entries.len(), 1);
    assert_eq!(tree.entries[0].provider, "A");
    let refused = svc.conflicts(&ConflictsRequest {
        instance: s(&root),
        profile: Some("Nope".to_owned()),
        mod_name: None,
    });
    assert!(matches!(refused, Err(ServiceError::Failed(_))));
}

#[test]
fn plugins_list_is_a_typed_read_only_report() {
    use raul_ui_service::PluginsRequest;
    let inst = Instance::new();
    let root = inst.root();
    profile(&root, "+A\r\n", "FalloutNV.esm\r\nA.esp\r\n");
    write_file(
        &root,
        "mods/A/A.esp",
        &nvmod_testkit::PluginBuilder::new()
            .requires("Lost.esm")
            .build(),
    );
    let report = service()
        .plugins_list(&PluginsRequest {
            instance: s(&root),
            profile: None,
        })
        .unwrap();
    assert_eq!(report.schema_version, 1);
    let a = report.plugins.iter().find(|p| p.name == "A.esp").unwrap();
    assert_eq!((a.position, a.active, a.installed), (2, true, true));
    assert_eq!(a.provider.as_deref(), Some("A"));
    assert_eq!(a.masters_missing, 1);
    let refused = service().plugins_list(&PluginsRequest {
        instance: s(&root),
        profile: Some("Nope".to_owned()),
    });
    assert!(matches!(refused, Err(ServiceError::Failed(_))));
}
