//! The Mod install and the MO2 import as direct jobs: a dry run prints the document the command line prints, a real
//! install writes `mods/` in process, a held Instance lock refuses it, and an import builds the Instance or reports
//! the disagreements. No game data is used; every path is a `TempDir`.

#![cfg(unix)]

mod common;

use common::{Instance, s};
use nvmod_testkit::{BaseBuilder, TempDir, ZipBuilder, write_file};
use raul_core::instance_lock::InstanceGuard;
use raul_ui_model::error::ExitClass;
use raul_ui_service::dto::InstallReport;
use raul_ui_service::exec::{Exec, Output};
use raul_ui_service::{
    CliService, ImportRequest, InProcessExec, InstallRequest, InstallResult, Service, ServiceError,
};

const HEADER: &str = "# This file was automatically generated by Mod Organizer.\r\n";

/// A runner that must never be asked for anything: the installs and the import are direct jobs.
struct Never;

impl Exec for Never {
    fn run(&self, args: &[String]) -> Result<Output, String> {
        panic!("a direct install or import must not run the command line: {args:?}");
    }
}

fn service() -> CliService<Never> {
    CliService::new(Never)
}

/// A synthetic MO2 instance with one Mod and one profile, whose `loadorder.txt` is `loadorder`.
fn mo2(dir: &std::path::Path, loadorder: &[u8]) {
    write_file(
        dir,
        "ModOrganizer.ini",
        b"[General]\r\ngameName=TTW\r\nselected_profile=@ByteArray(Example Profile)\r\n",
    );
    write_file(dir, "mods/Example Mod/meshes/rock.nif", b"rock");
    write_file(dir, "mods/Example Mod/Example Mod.esp", b"esp");
    let p = "profiles/Example Profile";
    write_file(
        dir,
        &format!("{p}/modlist.txt"),
        format!("{HEADER}+Example Mod\r\n").as_bytes(),
    );
    write_file(
        dir,
        &format!("{p}/plugins.txt"),
        format!("{HEADER}FalloutNV.esm\r\nExample Mod.esp\r\n").as_bytes(),
    );
    write_file(dir, &format!("{p}/loadorder.txt"), loadorder);
}

fn plain_archive(inst: &Instance) -> std::path::PathBuf {
    let zip = inst.work.path().join("Plain.zip");
    ZipBuilder::new().file("P.esp", b"plugin").write(&zip);
    zip
}

fn plain_request(inst: &Instance, archive: &str, dry_run: bool) -> InstallRequest {
    InstallRequest {
        archive: archive.to_owned(),
        instance: s(&inst.root()),
        profile: None,
        name: Some("Plain Mod".into()),
        dry_run,
        answers: None,
    }
}

#[test]
fn an_install_is_the_same_through_the_service_and_the_command_line() {
    let inst = Instance::new();
    let zip = plain_archive(&inst);
    let archive = s(&zip);
    let root = s(&inst.root());

    let answer = service()
        .install_mod(&plain_request(&inst, &archive, true))
        .unwrap();
    let InstallResult::Report(report) = answer else {
        panic!("expected a report for a dry run");
    };
    assert!(report.dry_run, "{report:?}");
    assert!(
        !inst.root().join("mods/Plain Mod").exists(),
        "a dry run writes nothing"
    );

    let words: Vec<String> = [
        "install",
        archive.as_str(),
        "--instance",
        root.as_str(),
        "--name",
        "Plain Mod",
        "--dry-run",
        "--json",
    ]
    .iter()
    .map(|w| (*w).to_owned())
    .collect();
    let cli = InProcessExec::new().run(&words).unwrap();
    assert_eq!(cli.code, Some(0), "{cli:?}");
    let cli_report: InstallReport = serde_json::from_str(&cli.stdout).unwrap();
    assert_eq!(report.mod_name, cli_report.mod_name);
    assert_eq!(report.plugins, cli_report.plugins);
    assert!(
        !inst.root().join("mods/Plain Mod").exists(),
        "the command line dry run writes nothing either"
    );

    let done = service()
        .install_mod(&plain_request(&inst, &archive, false))
        .unwrap();
    let InstallResult::Report(done) = done else {
        panic!("expected a report for the install");
    };
    assert!(!done.dry_run, "{done:?}");
    assert!(
        done.journal.is_some(),
        "an install leaves a journal to undo"
    );
    assert!(inst.root().join("mods/Plain Mod").is_dir());
}

#[test]
fn a_missing_archive_is_a_refusal() {
    let inst = Instance::new();
    let missing = s(&inst.work.path().join("missing.zip"));
    let err = service()
        .install_mod(&plain_request(&inst, &missing, false))
        .unwrap_err();
    let ServiceError::Failed(e) = err else {
        panic!("expected a failure, got {err:?}");
    };
    assert_eq!(e.exit, ExitClass::Refused, "{e:?}");
    assert!(!inst.root().join("mods/Plain Mod").exists());
}

#[test]
fn a_held_instance_lock_refuses_an_install() {
    let inst = Instance::new();
    let zip = plain_archive(&inst);
    let archive = s(&zip);
    let held = InstanceGuard::acquire(&inst.root(), "test").unwrap();
    let result = service().install_mod(&plain_request(&inst, &archive, false));
    drop(held);
    match result {
        Err(ServiceError::Failed(e)) => assert_eq!(e.exit, ExitClass::Refused, "{e:?}"),
        other => panic!("a held Instance lock refuses the install: {other:?}"),
    }
    assert!(!inst.root().join("mods/Plain Mod").exists());
}

#[test]
fn an_import_through_the_service_makes_the_instance_in_process() {
    let base = TempDir::new("direct-imp-base");
    BaseBuilder::steam().write(base.path());
    let mo2_dir = TempDir::new("direct-imp-mo2");
    mo2(
        mo2_dir.path(),
        format!("{HEADER}FalloutNV.esm\r\nExample Mod.esp\r\n").as_bytes(),
    );
    let out = TempDir::new("direct-imp-out");
    let new = out.path().join("new");

    service()
        .import_mo2(&ImportRequest {
            mo2: s(mo2_dir.path()),
            instance: s(&new),
            base: s(base.path()),
            profile: None,
            copy_only: true,
        })
        .unwrap();
    assert!(new.join("nvmod-instance.json").is_file());
}

#[test]
fn profile_files_that_disagree_are_blockers() {
    let base = TempDir::new("direct-dis-base");
    BaseBuilder::steam().write(base.path());
    let mo2_dir = TempDir::new("direct-dis-mo2");
    // The loadorder leaves out `Example Mod.esp`, which the plugins list enables.
    mo2(
        mo2_dir.path(),
        format!("{HEADER}FalloutNV.esm\r\n").as_bytes(),
    );
    let out = TempDir::new("direct-dis-out");
    let new = out.path().join("new");

    let err = service()
        .import_mo2(&ImportRequest {
            mo2: s(mo2_dir.path()),
            instance: s(&new),
            base: s(base.path()),
            profile: None,
            copy_only: true,
        })
        .unwrap_err();
    match err {
        ServiceError::Disagree(findings) => {
            assert!(!findings.is_empty(), "a disagreement has findings");
        }
        other @ ServiceError::Failed(_) => panic!("expected a disagreement, got {other:?}"),
    }
    assert!(!new.exists(), "nothing was written");
}
